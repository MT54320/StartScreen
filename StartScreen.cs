        void OnMouseMoveAll(object sender, MouseEventArgs e)
        {
            if (pressTile == null && pressGroup == null) return;
            var p = e.GetPosition(root);
            lastMouse = p;
            if (!dragging)
            {
                if (e.LeftButton != MouseButtonState.Pressed) { ResetPress(); return; }
                if (Math.Abs(p.X - pressPoint.X) + Math.Abs(p.Y - pressPoint.Y) < 10) return;
