        // Clicking anywhere outside the bar puts it away (clicking another tile just moves the selection).
        void OnPreviewDown(object sender, MouseButtonEventArgs e)
        {
            if (!barOpen) return;
            var d = e.OriginalSource as DependencyObject;
            if (IsInside(d, appBar)) return;
            if (barMode == "tile" && FindTagged(d, "tile") != null) return;
            if (barMode == "app" && FindTagged(d, "appitem") != null) return;
            CloseBar();
            e.Handled = true;
        }

        static DependencyObject TreeParent(DependencyObject d)
        {
            if (d is Visual || d is System.Windows.Media.Media3D.Visual3D) return VisualTreeHelper.GetParent(d);
            return LogicalTreeHelper.GetParent(d);
        }

        static bool IsInside(DependencyObject d, DependencyObject ancestor)
        {
            for (; d != null; d = TreeParent(d)) if (d == ancestor) return true;
            return false;
        }

        static FrameworkElement FindTagged(DependencyObject d, string tag)
        {
            for (; d != null; d = TreeParent(d))
            {
                var fe = d as FrameworkElement;
                if (fe != null && (fe.Tag as string) == tag) return fe;
            }
            return null;
        }

