        void BeginUninstall()
        {
            string exe = UninstallerPath();
            if (exe == null) { CancelUninstall(); return; }
            string args = "/uninstall /quiet" + (uninstallSettings ? " /removesettings" : "");
            if (uninstallSettings) noSave = true;        // don't write the layout back after the uninstaller deletes it

            // whole app fades to black, then it quits and the uninstaller removes it
            blackout.IsHitTestVisible = true;
            blackout.Visibility = Visibility.Visible;
            Action finish = () =>
            {
                try { Process.Start(new ProcessStartInfo(exe, args) { UseShellExecute = false, CreateNoWindow = true }); }
                catch (Exception ex) { App.Log(ex); }
                App.Exit();
            };
            if (!Anim) { blackout.Opacity = 1; finish(); return; }
            var fade = new DoubleAnimation(0, 1, TimeSpan.FromMilliseconds(1100)) { EasingFunction = new CubicEase { EasingMode = EasingMode.EaseInOut } };
            fade.Completed += (s, e) =>
            {
                var hold = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(350) };   // a beat of black before it closes
                hold.Tick += (s2, e2) => { hold.Stop(); finish(); };
                hold.Start();
            };
            blackout.BeginAnimation(OpacityProperty, fade);
        }

