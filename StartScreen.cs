            steps[3010] = () => shot("d-fader-early");
            steps[3150] = () => shot("e-fader-mid");
            steps[3900] = () => shot("f-fader-done");
            steps[4000] = () => GoPanel("settings-help");
            steps[4130] = () => shot("g-help-mid");
            steps[4900] = () => shot("h-help-done");
            // trackpad: post the same WM_MOUSEHWHEEL a sideways two-finger swipe produces, and watch the tiles move
            double off0 = 0, off1 = 0, off2 = 0;
            steps[5000] = () =>
            {
                ClosePanel(true);
                tilePanel.MinWidth = 4000;                      // make the tile area wider than the screen so there is something to scroll
                tileScroll.UpdateLayout();
                off0 = tileScroll.HorizontalOffset;
                Native.PostMessage(new WindowInteropHelper(this).Handle, 0x020E, (IntPtr)(240 << 16), IntPtr.Zero);   // swipe right
            };
            steps[5900] = () =>
            {
                off1 = tileScroll.HorizontalOffset;
                Native.PostMessage(new WindowInteropHelper(this).Handle, 0x020E, (IntPtr)((ushort)(-120 & 0xFFFF) << 16), IntPtr.Zero);   // swipe left
            };
            steps[6800] = () =>
            {
                off2 = tileScroll.HorizontalOffset;
                File.WriteAllText(Path.Combine(dir, "done.txt"), "scrollable=" + tileScroll.ScrollableWidth + " start=" + off0 + " afterRightSwipe=" + off1 + " afterLeftSwipe=" + off2
