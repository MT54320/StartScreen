        // The pattern is drawn once in white into a bitmap and used as a mask over the ink brush,
        // so recolouring is just a brush change (no redrawing).
        ImageSource PatternMask(string name, double w, double h, bool deviceRes)
        {
            string key = name + "|" + w + "|" + h;
            ImageSource cached;
            if (maskCache.TryGetValue(key, out cached)) return cached;
            double dpi = 1;
            if (deviceRes)
            {
                var src = PresentationSource.FromVisual(this);
                if (src != null && src.CompositionTarget != null) dpi = src.CompositionTarget.TransformToDevice.M11 * uiScale.ScaleX;
                dpi = Math.Min(dpi, 15000 / w);
            }
            var dv = new DrawingVisual();
            using (var dc = dv.RenderOpen()) dc.DrawDrawing(Patterns.Build(name, Colors.Transparent, Colors.White, w, h));
            var rtb = new RenderTargetBitmap(Math.Max(1, (int)(w * dpi)), Math.Max(1, (int)(h * dpi)), 96 * dpi, 96 * dpi, PixelFormats.Pbgra32);
            rtb.Render(dv);
            rtb.Freeze();
            maskCache[key] = rtb;
            return rtb;
        }

        static void SetBrush(SolidColorBrush b, Color c, int ms)
        {
            if (ms > 0) b.BeginAnimation(SolidColorBrush.ColorProperty, new ColorAnimation(c, TimeSpan.FromMilliseconds(ms)) { EasingFunction = new QuadraticEase { EasingMode = EasingMode.EaseOut } });
            else { b.BeginAnimation(SolidColorBrush.ColorProperty, null); b.Color = c; }
        }

        // Fades every themed colour to its new value over `ms` milliseconds (0 = instantly).
