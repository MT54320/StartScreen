        public static string Dir
        {
            get { return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "StartScreen8"); }
        }
        static string FilePath { get { return Path.Combine(Dir, "layout.json"); } }

        public static Config Load()
        {
            try
            {
                if (!File.Exists(FilePath)) return null;
                var c = new JavaScriptSerializer().Deserialize<Config>(File.ReadAllText(FilePath));
                if (c == null) return null;
                if (c.Groups == null) c.Groups = new List<GroupInfo>();
                if (c.Pattern == null) c.Pattern = "none";
                if (c.BgColor == null) c.BgColor = "";
                if (c.AccentColor == null) c.AccentColor = "";
                if (c.Background != "wallpaper") c.Background = "pattern";
                // v1.0-1.2 pinned an auto-generated "Control Panel" shortcut that actually opens Game Controllers.
                foreach (var g in c.Groups)
                    foreach (var t in g.Tiles)
                        if (t.Kind == "app" && t.Name == "Control Panel" && t.AppId != null && t.AppId.StartsWith("Microsoft.AutoGenerated", StringComparison.OrdinalIgnoreCase))
                            t.AppId = "Microsoft.Windows.ControlPanel";
                return c;
            }
            catch (Exception ex) { App.Log(ex); return null; }
        }

        public void Save()
        {
            try
            {
                Directory.CreateDirectory(Dir);
                File.WriteAllText(FilePath, new JavaScriptSerializer().Serialize(this));
            }
            catch (Exception ex) { App.Log(ex); }
        }

        // Applies what was chosen on the installer's colour and background pages (setup-choices.txt, one
        // line each: hue, then pattern). "-" means "the user didn't change this", so a reinstall never
        // overwrites colours the user already had. Returns true if anything changed. The file is consumed.
        public static bool ApplySetup(Config c)
        {
            bool changed = false;
            try
            {
                string cp = Path.Combine(Dir, "setup-colour.txt");
                if (!File.Exists(cp)) return false;
                var parts = File.ReadAllText(cp).Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
                double sh;
                if (parts.Length > 0 && double.TryParse(parts[0].Trim(), System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out sh))
                {
                    c.BgH = sh; c.AccentH = sh; c.BgShade = 0; c.AccentShade = 0;
                    c.BgColor = Colorx.Hex(Palette.Background(sh, 0));
                    c.AccentColor = Colorx.Hex(Palette.Accent(sh, 0));
                    changed = true;
                }
                if (parts.Length > 1)
                {
                    string pat = parts[1].Trim();
                    if (pat == "wallpaper") { c.Background = "wallpaper"; changed = true; }
                    else if (Array.IndexOf(Patterns.Names, pat) >= 0) { c.Background = "pattern"; c.Pattern = pat; changed = true; }
                }
                File.Delete(cp);
            }
            catch (Exception ex) { App.Log(ex); }
            return changed;
        }
    }

