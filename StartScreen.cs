            var pending = new Queue<KeyValuePair<int, Action>>(steps);
            var t = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(15) };
            t.Tick += (s, e) =>
            {
                while (pending.Count > 0 && clock.ElapsedMilliseconds >= pending.Peek().Key)
                {
                    var a = pending.Dequeue().Value;
                    try { a(); } catch (Exception ex) { App.Log(ex); }
                }
                if (pending.Count == 0) t.Stop();
            };
            t.Start();
        }

        static T FindDescendant<T>(DependencyObject d) where T : DependencyObject
        {
            if (d == null) return null;
            for (int i = 0; i < VisualTreeHelper.GetChildrenCount(d); i++)
            {
                var c = VisualTreeHelper.GetChild(d, i);
                var m = c as T ?? FindDescendant<T>(c);
                if (m != null) return m;
            }
            return null;
        }

        public void RunSnapshot(string dir, int width = 1600, int height = 900)
        {
            snapshot = true; modal = true;
            Directory.CreateDirectory(dir);
            WindowState = WindowState.Normal;
            Topmost = false; ShowActivated = false;
            Left = -6000; Top = 0; Width = width; Height = height;
            Show();
            var steps = new List<KeyValuePair<string, Action>>
            {
                new KeyValuePair<string, Action>("1-start", () => { root.Opacity = 1; onAppsPage = false; LayoutPages(); RebuildTiles(); }),
                new KeyValuePair<string, Action>("2-tilebar", () =>
                {
                    var g = config.Groups.FirstOrDefault(x => x.Tiles.Any(t => t.Kind == "app"));
                    if (g != null) ShowTileBar(g.Tiles.First(t => t.Kind == "app"), g);
                }),
                new KeyValuePair<string, Action>("3-startbar", () => { CloseBar(true); ShowStartBar(); }),
                new KeyValuePair<string, Action>("4-zoomed", () => { CloseBar(true); SetZoomInstant(true); }),
                new KeyValuePair<string, Action>("5-personalize", () => { SetZoomInstant(false); ShowPanel("personalize"); }),
                new KeyValuePair<string, Action>("6-settings", () => { ShowPanel("settings"); }),
                new KeyValuePair<string, Action>("6b-tiles", () => { GoPanel("settings-tiles"); }),
                new KeyValuePair<string, Action>("6c-help", () => { GoPanel("settings-help"); }),
                new KeyValuePair<string, Action>("7-apps", () => { ClosePanel(true); onAppsPage = true; LayoutPages(); }),
                new KeyValuePair<string, Action>("7b-appbar", () => { var a = apps.FirstOrDefault(x => x.Name == "Discord") ?? apps.FirstOrDefault(); if (a != null) ShowAppBar(a); }),
                new KeyValuePair<string, Action>("8-search", () => { searchBox.Text = "ste"; }),
                new KeyValuePair<string, Action>("9-uninstall", () => { searchBox.Text = ""; onAppsPage = false; LayoutPages(); ShowUninstall(); }),
            };
            int i = -1;
            var timer = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(700) };
            Action next = null;
            next = () =>
            {
                if (i >= 0) SavePng(root, Path.Combine(dir, steps[i].Key + ".png"));
                i++;
                if (i >= steps.Count)
                {
                    timer.Stop();
                    DumpIcons(Path.Combine(dir, "icons"));
                    App.Exit();
                    return;
                }
                try { steps[i].Value(); } catch (Exception ex) { App.Log(ex); }
            };
            timer.Tick += (s, e) => next();
            CatalogLoaded += () => { if (!timer.IsEnabled && i < 0) timer.Start(); };
        }

        static void SavePng(FrameworkElement el, string path)
        {
            el.UpdateLayout();
            // the root is shown through a scale (UpdateScale), so capture at the on-screen size, not the layout size
            var st = el.LayoutTransform as ScaleTransform;
            double sx = st != null ? st.ScaleX : 1, sy = st != null ? st.ScaleY : 1;
            var rtb = new RenderTargetBitmap(Math.Max(1, (int)Math.Round(el.ActualWidth * sx)), Math.Max(1, (int)Math.Round(el.ActualHeight * sy)), 96, 96, PixelFormats.Pbgra32);
            rtb.Render(el);
            var enc = new PngBitmapEncoder();
            enc.Frames.Add(BitmapFrame.Create(rtb));
            using (var fs = File.Create(path)) enc.Save(fs);
        }

        void DumpIcons(string dir)
        {
            Directory.CreateDirectory(dir);
            var lines = new List<string>();
            foreach (var g in config.Groups)
                foreach (var t in g.Tiles)
                {
                    AppEntry a;
                    if (t.AppId == null || !byId.TryGetValue(t.AppId, out a)) continue;
                    lines.Add(a.Name + " | " + a.Id + " | iconPx=" + a.IconPx + " | color=" + (a.HasColor ? Colorx.Hex(a.TileColor) : "accent"));
                    var bs = a.Icon as BitmapSource;
                    if (bs == null) continue;
                    var enc = new PngBitmapEncoder();
                    enc.Frames.Add(BitmapFrame.Create(bs));
                    string safe = string.Concat(a.Name.Where(ch => char.IsLetterOrDigit(ch) || ch == ' '));
                    using (var fs = File.Create(Path.Combine(dir, safe + ".png"))) enc.Save(fs);
                }
            File.WriteAllLines(Path.Combine(dir, "icons.txt"), lines);
        }
