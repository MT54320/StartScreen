        public static void Log(Exception ex)
        {
            try
            {
                Directory.CreateDirectory(Config.Dir);
                File.AppendAllText(Path.Combine(Config.Dir, "log.txt"), DateTime.Now.ToString("s") + "  " + ex + Environment.NewLine);
            }
            catch { }
        }

        [STAThread]
        public static void Main(string[] args)
        {
            // This machine reports a tablet device, so WPF tries to promote mouse capture to touch and
            // throws inside ChangeMouseCapture (StylusPointDescription). That capture path is what tile
            // dragging uses, so the fault can break drag-to-rearrange. Turning off WPF's stylus/touch
            // stack makes touch fall back to plain mouse input and removes the fault. Must run first.
            AppContext.SetSwitch("Switch.System.Windows.Input.Stylus.DisableStylusAndTouchSupport", true);

            // /snapshot <folder>: render the UI to PNG files and quit (used for checking the design)
            int si = Array.FindIndex(args, a => a.Equals("/snapshot", StringComparison.OrdinalIgnoreCase));
            if (si >= 0 && si + 1 < args.Length)
            {
                var sapp = new Application { ShutdownMode = ShutdownMode.OnExplicitShutdown };
                sapp.DispatcherUnhandledException += (s, e) => { Log(e.Exception); e.Handled = true; };
                Styles.Install(sapp);
                window = new StartWindow();
                int zi = Array.FindIndex(args, a => a.Equals("/size", StringComparison.OrdinalIgnoreCase));
                int sw = 1600, sh = 900;
                if (zi >= 0 && zi + 1 < args.Length)
                {
                    var wh = args[zi + 1].ToLowerInvariant().Split('x');
                    int pw, ph;
                    if (wh.Length == 2 && int.TryParse(wh[0], out pw) && int.TryParse(wh[1], out ph)) { sw = pw; sh = ph; }
                }
                window.RunSnapshot(args[si + 1], sw, sh);
                window.RefreshCatalog();
                sapp.Run();
                return;
            }

            // /plans <file>: dry run - write what Uninstall would do for every app, without removing anything
            int pi = Array.FindIndex(args, a => a.Equals("/plans", StringComparison.OrdinalIgnoreCase));
            if (pi >= 0 && pi + 1 < args.Length)
            {
                var lines = new List<string>();
                foreach (var a in AppCatalog.Enumerate())
                {
                    try
                    {
                        var p = Uninstaller.Make(a.Id, a.Name, AppCatalog.TargetOf(a.Id, a.Name), AppCatalog.ShortcutOf(a.Name));
                        lines.Add(a.Name + "  =>  " + p.Kind + (p.Kind == "program" ? " | " + p.Title + " | " + p.Exe + " " + p.Args + (p.Elevate ? " [admin]" : "") : ""));
                    }
                    catch (Exception ex) { lines.Add(a.Name + "  =>  error " + ex.Message); }
                }
                File.WriteAllLines(args[pi + 1], lines);
                return;
            }

            bool background = args.Any(a => a.Equals("/background", StringComparison.OrdinalIgnoreCase));
            bool created;
            var mutex = new Mutex(true, @"Local\StartScreen8.Instance", out created);
            var showEvent = new EventWaitHandle(false, EventResetMode.AutoReset, @"Local\StartScreen8.Show");
            if (!created)
            {
                showEvent.Set();
                return;
            }

            var app = new Application { ShutdownMode = ShutdownMode.OnExplicitShutdown };
            app.DispatcherUnhandledException += (s, e) => { Log(e.Exception); e.Handled = true; };
            Styles.Install(app);

            window = new StartWindow();
            new WindowInteropHelper(window).EnsureHandle();
            window.AttachHook();
            // The installer starts us hidden while it shows its "getting ready" screen and waits on this event,
            // so every app and icon is already loaded by the time you open Start for the first time.
            loadedEvent = new EventWaitHandle(false, EventResetMode.ManualReset, @"Local\StartScreen8.Loaded");
            window.CatalogLoaded += () => { try { loadedEvent.Set(); } catch { } };
            window.RefreshCatalog();

            hook = new WinKeyHook();
            hook.Enabled = window.Settings == null || window.Settings.WinKey;
            hook.WinPressed += () => window.Dispatcher.BeginInvoke(new Action(window.ToggleStart));
            hook.Install();

            startHook = new StartButtonHook();
            startHook.Enabled = window.Settings == null || window.Settings.StartButton;
            startHook.Clicked += () => window.Dispatcher.BeginInvoke(new Action(window.ShowStart));
            window.IsVisibleChanged += (s, e) => startHook.Open = window.IsVisible;
            startHook.Install();

            var waiter = new Thread(() =>
            {
                while (true)
                {
                    showEvent.WaitOne();
                    window.Dispatcher.BeginInvoke(new Action(window.ShowStart));
                }
            });
            waiter.IsBackground = true;
            waiter.Start();

            SetupTray();
            if (!background) window.Dispatcher.BeginInvoke(new Action(window.ShowStart), DispatcherPriority.ApplicationIdle);
            int tp = Array.FindIndex(args, a => a.Equals("/selftest-panel", StringComparison.OrdinalIgnoreCase));
            if (tp >= 0 && tp + 1 < args.Length)
            {
                string tpDir = args[tp + 1];
                window.Dispatcher.BeginInvoke(new Action(() => window.SelfTestPanel(tpDir)), DispatcherPriority.ApplicationIdle);
            }
            if (args.Any(a => a.Equals("/selftest-uninstall", StringComparison.OrdinalIgnoreCase)))
                window.Dispatcher.BeginInvoke(new Action(window.SelfTestUninstall), DispatcherPriority.ApplicationIdle);

            app.Run();

            hook.Uninstall();
            if (startHook != null) startHook.Uninstall();
            tray.Visible = false;
            tray.Dispose();
            GC.KeepAlive(mutex);
        }

        static System.Drawing.Icon MakeTrayIcon()
        {
            // use the icon embedded in the exe (the same tile-layout artwork as the shortcuts)
            try { return System.Drawing.Icon.ExtractAssociatedIcon(Process.GetCurrentProcess().MainModule.FileName); } catch { }
            var bmp = new System.Drawing.Bitmap(32, 32);
            using (var g = System.Drawing.Graphics.FromImage(bmp))
            {
                g.Clear(System.Drawing.Color.Transparent);
                var c = Colorx.SystemAccent();
                using (var b = new System.Drawing.SolidBrush(System.Drawing.Color.FromArgb(c.R, c.G, c.B)))
                using (var w = new System.Drawing.SolidBrush(System.Drawing.Color.White))
                {
                    g.FillRectangle(b, 1, 1, 30, 30);
                    g.FillRectangle(w, 6, 6, 9, 9);
                    g.FillRectangle(w, 17, 6, 9, 9);
                    g.FillRectangle(w, 6, 17, 20, 9);
                }
            }
            return System.Drawing.Icon.FromHandle(bmp.GetHicon());
        }

