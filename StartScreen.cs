                            for (double t = 0.1; t < 40; t += 0.12) c.LineTo(new Point(cx + Math.Cos(t) * a * t, cy + Math.Sin(t) * a * t), true, true);
                        }
                        dg.Children.Add(new GeometryDrawing(null, new Pen(fill(0.12 + rnd.NextDouble() * 0.15), 2 + rnd.NextDouble() * 3), sg));
                    }
                    break;
                case "crosses":
                    {
                        var buckets = new StreamGeometry[4];
                        var ctxs = new StreamGeometryContext[4];
                        for (int i = 0; i < 4; i++) { buckets[i] = new StreamGeometry(); ctxs[i] = buckets[i].Open(); }
                        for (double x = 25; x < w; x += 50)
                            for (double y = 25; y < h; y += 50)
                            {
                                var c = ctxs[rnd.Next(4)];
                                c.BeginFigure(new Point(x - 8, y), false, false); c.LineTo(new Point(x + 8, y), true, false);
                                c.BeginFigure(new Point(x, y - 8), false, false); c.LineTo(new Point(x, y + 8), true, false);
                            }
                        for (int i = 0; i < 4; i++) { ctxs[i].Close(); dg.Children.Add(new GeometryDrawing(null, new Pen(fill(0.08 + i * 0.08), 3), buckets[i])); }
                        break;
                    }
                case "ribbons":
                    for (int i = 0; i < 9; i++)
                    {
                        var sg = new StreamGeometry();
                        using (var c = sg.Open())
                        {
                            double y0 = rnd.NextDouble() * h;
                            c.BeginFigure(new Point(-100, y0), false, false);
                            for (double x = 0; x < w + 400; x += 800)
                                c.BezierTo(new Point(x + 200, rnd.NextDouble() * h), new Point(x + 600, rnd.NextDouble() * h), new Point(x + 800, y0 + (rnd.NextDouble() - 0.5) * 200), true, true);
                        }
                        dg.Children.Add(new GeometryDrawing(null, new Pen(fill(0.06 + rnd.NextDouble() * 0.12), 20 + rnd.NextDouble() * 70), sg));
                    }
                    break;
            }
            dg.ClipGeometry = new RectangleGeometry(full);
            dg.Freeze();
            return dg;
        }

        static void Circle(StreamGeometryContext c, double x, double y, double r, bool filled)
        {
            c.BeginFigure(new Point(x + r, y), filled, true);
            c.ArcTo(new Point(x - r, y), new Size(r, r), 0, false, SweepDirection.Clockwise, true, false);
            c.ArcTo(new Point(x + r, y), new Size(r, r), 0, false, SweepDirection.Clockwise, true, false);
        }
