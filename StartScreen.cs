        // Small square mask of a pattern for the Personalize grid (drawn once per pattern, colour comes from the brushes).
        ImageSource ThumbMask(string name)
        {
            string key = "thumb|" + name;
            ImageSource cached;
            if (maskCache.TryGetValue(key, out cached)) return cached;
            const int px = 120;
            var dv = new DrawingVisual();
            using (var dc = dv.RenderOpen())
            {
                dc.PushTransform(new ScaleTransform(px / 1080.0, px / 1080.0));
                dc.PushClip(new RectangleGeometry(new Rect(0, 0, 1080, 1080)));
                dc.DrawDrawing(Patterns.Build(name, Colors.Transparent, Colors.White, 1800, 1080));
            }
            var rtb = new RenderTargetBitmap(px, px, 96, 96, PixelFormats.Pbgra32);
            rtb.Render(dv);
            rtb.Freeze();
            maskCache[key] = rtb;
            return rtb;
        }

