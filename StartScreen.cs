        // The rainbow slider under each grid: one smooth gradient with a thumb that follows the mouse exactly.
        FrameworkElement HueStrip(double current, Action<double> pick, Action done)
        {
            const double W = 300, ThumbW = 8;
            var host = new Grid { Width = W, Height = 26, Margin = new Thickness(0, 6, 0, 0), Background = Brushes.Transparent, Cursor = Cursors.Hand, HorizontalAlignment = HorizontalAlignment.Left };
            host.Children.Add(new Border { Height = 12, VerticalAlignment = VerticalAlignment.Center, Background = Palette.StripBrush() });
