            var thumb = new Border { Width = ThumbW, Height = 26, Background = Brushes.White, BorderBrush = Colorx.Brush(0x99, 0, 0, 0), BorderThickness = new Thickness(1) };
            canvas.Children.Add(thumb);
            host.Children.Add(canvas);
            Action<double> place = x => Canvas.SetLeft(thumb, Math.Max(0, Math.Min(W - ThumbW, x * W - ThumbW / 2)));
            place(Palette.XOf(current));
            double last = -2;
            Action<MouseEventArgs> move = e =>
            {
                double x = Math.Max(0, Math.Min(1, e.GetPosition(host).X / W));
                place(x);
                double hue = Palette.HueAt(x);
                if (Math.Abs(hue - last) < 0.25) return;
                last = hue;
                pick(hue);
            };
            host.MouseLeftButtonDown += (s, e) => { host.CaptureMouse(); move(e); e.Handled = true; };
            host.MouseMove += (s, e) => { if (host.IsMouseCaptured) move(e); };
            host.MouseLeftButtonUp += (s, e) =>
            {
                e.Handled = true;
                if (!host.IsMouseCaptured) return;
                host.ReleaseMouseCapture();
                Dispatcher.BeginInvoke(done);
            };
            return host;
        }

