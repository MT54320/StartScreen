        static void SizeCells(string size, out int w, out int h)
        {
            switch (size)
            {
                case "small": w = 1; h = 1; break;
                case "wide": w = 4; h = 2; break;
                case "large": w = 4; h = 4; break;
                default: w = 2; h = 2; break;
            }
        }

        int Rows()
        {
            double area = VH - 150 - 80 - 44;
            int rows = (int)((area + Gap) / Cell);
            rows = rows / 2 * 2;
            return Math.Max(4, Math.Min(8, rows));
        }

        void RebuildTiles() { Render(config != null ? config.Groups : null, null, null); }

        void Render(List<GroupInfo> groups, TileInfo ghostTile, GroupInfo ghostGroup)
        {
            if (groups == null || tilePanel == null) return;

            bool animate = Anim && IsVisible && !hiding && groupViews.Count > 0;
            var oldTiles = new Dictionary<TileInfo, Rect>();
            var oldGroups = new Dictionary<GroupInfo, double>();
            if (animate)
            {
                foreach (var gv in groupViews)
                {
                    var gr = BoundsIn(gv.Panel, tilePanel);
                    if (!gr.IsEmpty) oldGroups[gv.G] = gr.Left;
                    foreach (var tv in gv.Tiles)
                    {
                        var tr = BoundsIn(tv.El, tilePanel);
                        if (!tr.IsEmpty) oldTiles[tv.T] = tr;
                    }
                }
            }

            clocks.Clear();
            groupViews.Clear();
            tilePanel.Children.Clear();
            int rows = Rows();
            foreach (var g in groups)
            {
                var gv = MakeGroup(g, rows, ghostTile);
                if (g == ghostGroup) gv.Panel.Opacity = 0.25;
                groupViews.Add(gv);
                tilePanel.Children.Add(gv.Panel);
            }
            tilePanel.Children.Add(new Border { Width = 260, Background = Brushes.Transparent });
            UpdateClocks();
            if (animate) AnimateFrom(oldTiles, oldGroups);
            if (pendingRename != null && !zoomedOut)
            {
                var gr = pendingRename; pendingRename = null;
                var gv = groupViews.FirstOrDefault(x => x.G == gr);
                if (gv != null) Dispatcher.BeginInvoke(new Action(() => { ScrollToGroup(gr); var a = gv.Panel.Tag as Action; if (a != null) a(); }), DispatcherPriority.Loaded);
            }
        }

        // Moves/resizes every tile and group from its old spot to its new one with an ease, instead of snapping.
        void AnimateFrom(Dictionary<TileInfo, Rect> oldTiles, Dictionary<GroupInfo, double> oldGroups)
        {
            tilePanel.UpdateLayout();
            var ease = new CubicEase { EasingMode = EasingMode.EaseOut };
            var groupDx = new Dictionary<GroupInfo, double>();
            var newTiles = new Dictionary<TileView, Rect>();
            foreach (var gv in groupViews)
            {
                var gr = BoundsIn(gv.Panel, tilePanel);
                double old;
                groupDx[gv.G] = (!gr.IsEmpty && oldGroups.TryGetValue(gv.G, out old)) ? old - gr.Left : 0;
                foreach (var tv in gv.Tiles) newTiles[tv] = BoundsIn(tv.El, tilePanel);
            }
            foreach (var gv in groupViews)
            {
                double gdx = groupDx[gv.G];
                if (Math.Abs(gdx) > 0.5)
                {
                    var tt = gv.Panel.RenderTransform as TranslateTransform;
                    if (tt == null) { tt = new TranslateTransform(); gv.Panel.RenderTransform = tt; }
                    tt.BeginAnimation(TranslateTransform.XProperty, new DoubleAnimation(gdx, 0, MoveTime) { EasingFunction = ease });
                }
                foreach (var tv in gv.Tiles)
                {
                    Rect old, now = newTiles[tv];
                    if (now.IsEmpty) continue;
                    if (!oldTiles.TryGetValue(tv.T, out old))
                    {
                        tv.El.BeginAnimation(OpacityProperty, new DoubleAnimation(0, 1, MoveTime));
                        continue;
                    }
                    double left = Canvas.GetLeft(tv.El), top = Canvas.GetTop(tv.El);
                    double dx = old.X - now.X - gdx, dy = old.Y - now.Y;
                    if (Math.Abs(dx) > 0.5) tv.El.BeginAnimation(Canvas.LeftProperty, new DoubleAnimation(left + dx, left, MoveTime) { EasingFunction = ease });
                    if (Math.Abs(dy) > 0.5) tv.El.BeginAnimation(Canvas.TopProperty, new DoubleAnimation(top + dy, top, MoveTime) { EasingFunction = ease });
                    if (Math.Abs(old.Width - now.Width) > 1) tv.El.BeginAnimation(WidthProperty, new DoubleAnimation(old.Width, now.Width, MoveTime) { EasingFunction = ease });
                    if (Math.Abs(old.Height - now.Height) > 1) tv.El.BeginAnimation(HeightProperty, new DoubleAnimation(old.Height, now.Height, MoveTime) { EasingFunction = ease });
                }
            }
        }

        GroupView MakeGroup(GroupInfo g, int rows, TileInfo ghostTile)
        {
            var gv = new GroupView { G = g };
            var panel = new StackPanel { Margin = new Thickness(0, 0, GroupGap, 0), RenderTransform = new TranslateTransform(), Background = Brushes.Transparent };
            gv.Panel = panel;

            // Zoomed out, names are drawn big (they get scaled down) and get a taller header so they never run into the tiles.
            var header = new Grid { Height = zoomedOut ? 120 : 44, Background = Brushes.Transparent, HorizontalAlignment = HorizontalAlignment.Left };
            var label = new TextBlock
            {
                Text = g.Name, FontFamily = Semilight, FontSize = zoomedOut ? 64 : 20, VerticalAlignment = VerticalAlignment.Top,
                TextTrimming = TextTrimming.CharacterEllipsis, TextWrapping = TextWrapping.NoWrap
            };
            var box = new TextBox
            {
                Text = g.Name, FontSize = 18, Visibility = Visibility.Collapsed, VerticalAlignment = VerticalAlignment.Top, MinWidth = 230,
                HorizontalAlignment = HorizontalAlignment.Left, Background = Colorx.Brush(0xEE, 255, 255, 255), BorderThickness = new Thickness(0), Padding = new Thickness(6, 3, 6, 3)
            };
            header.Children.Add(label);
            header.Children.Add(box);
            Action commit = () =>
            {
                if (box.Visibility != Visibility.Visible) return;
                box.Visibility = Visibility.Collapsed;
                g.Name = box.Text.Trim();
                Save();
                Dispatcher.BeginInvoke(new Action(RebuildTiles));
                Keyboard.Focus(this);
            };
            box.PreviewKeyDown += (s, e) =>
            {
                if (e.Key == Key.Enter) { commit(); e.Handled = true; }
                else if (e.Key == Key.Escape) { box.Visibility = Visibility.Collapsed; label.Visibility = Visibility.Visible; Keyboard.Focus(this); e.Handled = true; }
            };
            box.LostKeyboardFocus += (s, e) => commit();
            Action startRename = () =>
            {
                label.Visibility = Visibility.Collapsed;
                box.Text = g.Name;
                box.Visibility = Visibility.Visible;
                box.Focus(); box.SelectAll();
            };
            panel.Tag = startRename;

            if (!zoomedOut)
            {
                if (string.IsNullOrEmpty(g.Name))
                {
                    header.MouseEnter += (s, e) => { if (box.Visibility != Visibility.Visible) { label.Text = "Name group"; label.Opacity = 0.5; } };
                    header.MouseLeave += (s, e) => { label.Text = ""; label.Opacity = 1; };
                    header.MouseLeftButtonDown += (s, e) => { startRename(); e.Handled = true; };
                }
                else header.MouseLeftButtonDown += (s, e) => { if (e.ClickCount == 2) { startRename(); e.Handled = true; } };
                header.Cursor = Cursors.IBeam;
            }
            header.MouseRightButtonUp += (s, e) => { ShowGroupBar(g); e.Handled = true; };
            panel.Children.Add(header);

            const int MaxCols = 400;
            var occ = new bool[rows, MaxCols];
            int usedCols = 0;
            var canvas = new Canvas { Background = Brushes.Transparent, Height = rows * Cell - Gap, IsHitTestVisible = !zoomedOut };
            foreach (var t in g.Tiles)
            {
                int w, h;
                SizeCells(t.Size, out w, out h);
                if (h > rows) h = rows;
                int align = w == 1 ? 1 : 2;
                bool placed = false;
                for (int c = 0; c + w <= MaxCols && !placed; c += align)
                    for (int r = 0; r + h <= rows && !placed; r += align)
                    {
                        bool fits = true;
                        for (int dc = 0; dc < w && fits; dc++)
                            for (int dr = 0; dr < h && fits; dr++)
                                if (occ[r + dr, c + dc]) fits = false;
                        if (!fits) continue;
                        for (int dc = 0; dc < w; dc++)
                            for (int dr = 0; dr < h; dr++)
                                occ[r + dr, c + dc] = true;
                        double pw = w * Cell - Gap, ph = h * Cell - Gap;
                        FrameworkElement el = t == ghostTile
                            ? (FrameworkElement)new Border { Width = pw, Height = ph, Background = Colorx.Brush(0x18, 255, 255, 255), BorderBrush = Colorx.Brush(0x50, 255, 255, 255), BorderThickness = new Thickness(1) }
                            : MakeTile(t, g, pw, ph);
                        Canvas.SetLeft(el, c * Cell);
                        Canvas.SetTop(el, r * Cell);
                        canvas.Children.Add(el);
                        gv.Tiles.Add(new TileView { T = t, El = el });
                        usedCols = Math.Max(usedCols, c + w);
                        placed = true;
                    }
            }
            canvas.Width = Math.Max(2, usedCols) * Cell - Gap;
            label.MaxWidth = canvas.Width;
            panel.Children.Add(canvas);

            if (zoomedOut)
            {
                panel.Background = Colorx.Brush(0x01, 255, 255, 255);
                panel.Cursor = Cursors.Hand;
