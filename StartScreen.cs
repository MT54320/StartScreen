            [PreserveSig] int GetMasterVolumeLevel(out float db);
            [PreserveSig] int GetMasterVolumeLevelScalar(out float level);
        }

        static IAudioEndpointVolume Endpoint()
        {
            try
            {
                var en = (IMMDeviceEnumerator)new MMDeviceEnumerator();
                IMMDevice dev;
                if (en.GetDefaultAudioEndpoint(0 /*render*/, 1 /*multimedia*/, out dev) != 0 || dev == null) return null;
                Guid iid = typeof(IAudioEndpointVolume).GUID;
                object o;
                if (dev.Activate(ref iid, 23, IntPtr.Zero, out o) != 0) return null;
                return o as IAudioEndpointVolume;
            }
            catch (Exception ex) { App.Log(ex); return null; }
        }

        public static int GetVolume()
        {
            var ep = Endpoint();
            float l;
            if (ep == null || ep.GetMasterVolumeLevelScalar(out l) != 0) return -1;
            return (int)Math.Round(l * 100);
        }

        public static void SetVolume(int v)
        {
            var ep = Endpoint();
            if (ep == null) return;
            Guid g = Guid.Empty;
            ep.SetMasterVolumeLevelScalar(Math.Max(0, Math.Min(100, v)) / 100f, ref g);
        }
    }

    // Screen brightness through WMI (laptops / tablets; desktop monitors usually say "Unavailable", like 8.1).
    static class Brightness
    {
        static readonly object gate = new object();
        static int pending = -1;
        static bool running;

        public static int Get()
        {
            try
            {
                using (var s = new System.Management.ManagementObjectSearcher(new System.Management.ManagementScope(@"root\WMI"), new System.Management.SelectQuery("SELECT CurrentBrightness FROM WmiMonitorBrightness")))
                    foreach (System.Management.ManagementObject o in s.Get()) return Convert.ToInt32(o["CurrentBrightness"]);
            }
            catch { }
            return -1;
        }

        public static void Set(int v)
        {
            lock (gate) { pending = v; if (running) return; running = true; }
            ThreadPool.QueueUserWorkItem(_ =>
            {
                while (true)
                {
                    int val;
                    lock (gate) { if (pending < 0) { running = false; return; } val = pending; pending = -1; }
                    try
                    {
                        using (var s = new System.Management.ManagementObjectSearcher(new System.Management.ManagementScope(@"root\WMI"), new System.Management.SelectQuery("SELECT * FROM WmiMonitorBrightnessMethods")))
                            foreach (System.Management.ManagementObject o in s.Get()) o.InvokeMethod("WmiSetBrightness", new object[] { (uint)1, (byte)val });
                    }
                    catch { }
                }
            });
        }
    }

