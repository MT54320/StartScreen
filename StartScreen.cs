        void Uninstall(FrameworkElement anchor, string id, string name)
        {
            var plan = Uninstaller.Make(id, name, AppCatalog.TargetOf(id, name), AppCatalog.ShortcutOf(name));
            string text, button = "Uninstall";
            switch (plan.Kind)
            {
                case "store": text = "“" + name + "” and its info will be uninstalled."; break;
                case "program": text = "This will uninstall “" + plan.Title + "”." + (plan.Elevate ? " Windows will ask for permission." : ""); break;
                case "steam": text = "Steam will uninstall “" + name + "”."; break;
                case "shortcut": text = "No uninstaller was found for “" + name + "”. Delete it from Start instead?"; button = "Delete"; break;
                case "system": Toast("“" + name + "” is part of Windows and can't be uninstalled."); return;
                default: Toast("No uninstaller was found for “" + name + "”."); return;
            }
            ConfirmFlyout(anchor, text, button, () =>
            {
                CloseBar();
                Toast((plan.Kind == "shortcut" ? "Removing " : "Uninstalling ") + name + "…", true);
                // keep Start open (but not on top) so permission prompts and uninstaller windows can show
                modal = true; Topmost = false;
                Uninstaller.Run(plan, (res, msg) => Dispatcher.BeginInvoke(new Action(() =>
                {
                    modal = false; Topmost = true;
                    Toast(msg);
                    if (res == "done")
                    {
                        Unpin(id);
                        lastRefresh = DateTime.MinValue;
                        RefreshCatalog();
                    }
                })));
            });
        }

