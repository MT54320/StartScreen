                var grid = FindDescendant<System.Windows.Controls.Primitives.UniformGrid>(sidePanel);
                if (grid != null && grid.Children.Count > 1)
                {
                    var btn = (UIElement)grid.Children[1];
                    btn.RaiseEvent(new MouseButtonEventArgs(Mouse.PrimaryDevice, Environment.TickCount, MouseButton.Left) { RoutedEvent = UIElement.MouseLeftButtonUpEvent, Source = btn });
                }
