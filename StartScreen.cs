        void UpdateScale()
        {
            double w = ActualWidth, h = ActualHeight;
            if (w <= 0 || h <= 0) return;
            double s = Math.Min(w / 1920.0, h / 1080.0);
            if (s > 0.9 && s < 1.1) s = 1;
            s = Math.Max(0.55, Math.Min(2.6, s));
            if (Math.Abs(uiScale.ScaleX - s) > 0.001) { uiScale.ScaleX = s; uiScale.ScaleY = s; maskCache.Clear(); }
        }

