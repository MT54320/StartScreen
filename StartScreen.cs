        IntPtr HwndHook(IntPtr hwnd, int msg, IntPtr wParam, IntPtr lParam, ref bool handled)
        {
            if (msg == 0x020E)
            {
                hwheelSeen++;
                short delta = (short)((wParam.ToInt64() >> 16) & 0xFFFF);
