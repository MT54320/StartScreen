        public event Action CatalogLoaded;

        public void RefreshCatalog()
        {
            if (loading) return;
            loading = true;
            lastRefresh = DateTime.Now;
            AppCatalog.ResetShortcuts();
            var th = new Thread(() =>
            {
                List<AppEntry> list = null;
                try { list = AppCatalog.Enumerate(); } catch (Exception ex) { App.Log(ex); }
                if (list == null) list = new List<AppEntry>();
                foreach (var a in list)
                {
                    AppEntry cached;
                    if (iconCache.TryGetValue(a.Id, out cached)) { a.Icon = cached.Icon; a.IconPx = cached.IconPx; a.TileColor = cached.TileColor; a.HasColor = cached.HasColor; }
                }
                var snapshotList = list;
                Dispatcher.BeginInvoke(new Action(() => OnAppsEnumerated(snapshotList)));

                IconLoader.ResetPackages();
                // pinned apps first so the tiles sharpen up quickly
                var pinned = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                var cfg = config;
                if (cfg != null) foreach (var g in cfg.Groups.ToList()) foreach (var t in g.Tiles.ToList()) if (t.AppId != null) pinned.Add(t.AppId);
                bool any = false;
                foreach (var a in list.OrderBy(x => pinned.Contains(x.Id) ? 0 : 1).ToList())
                {
                    if (iconCache.ContainsKey(a.Id)) continue;
                    try { IconLoader.Load(a); } catch (Exception ex) { App.Log(ex); }
                    iconCache[a.Id] = a;
                    any = true;
                }
                Dispatcher.BeginInvoke(new Action(() =>
                {
                    loading = false;
                    if (any && !dragging) { RebuildTiles(); RebuildApps(); }
                    var h = CatalogLoaded; if (h != null) h();
                }));
            });
            th.SetApartmentState(ApartmentState.STA);
            th.IsBackground = true;
            th.Start();
        }

