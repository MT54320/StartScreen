        void StartDrag()
        {
            dragging = true;
            preview = config.Groups.Select(x => x.CloneShallow()).ToList();
            if (pressTile != null)
            {
                int w, h;
                SizeCells(pressTile.Size, out w, out h);
                var face = MakeTileFace(pressTile, w * Cell - Gap, h * Cell - Gap);
                face.Opacity = 0.92;
                face.RenderTransformOrigin = new Point(0.5, 0.5);
                face.RenderTransform = new ScaleTransform(1.05, 1.05);
                face.Effect = new System.Windows.Media.Effects.DropShadowEffect { BlurRadius = 24, ShadowDepth = 4, Opacity = 0.5 };
                ghost = face;
            }
            else
            {
                var size = pressEl.RenderSize;
                var snap = new RenderTargetBitmap(Math.Max(1, (int)size.Width), Math.Max(1, (int)size.Height), 96, 96, PixelFormats.Pbgra32);
                snap.Render(pressEl);
                snap.Freeze();
                ghost = new Border
                {
                    Width = size.Width * zoom.ScaleX, Height = size.Height * zoom.ScaleY,
                    Background = new ImageBrush(snap) { Stretch = Stretch.Fill },
                    BorderBrush = Brushes.White, BorderThickness = new Thickness(1.5), Opacity = 0.95
                };
            }
            overlay.Children.Add(ghost);
            if (pressTile != null) Render(preview, pressTile, null);
            else Render(preview, null, preview[config.Groups.IndexOf(pressGroup)]);
            edgeScroll.Start();
        }

        void UpdateDrag(Point p)
        {
            if (ghost != null)
            {
                Canvas.SetLeft(ghost, p.X - grabOffset.X);
                Canvas.SetTop(ghost, p.Y - grabOffset.Y);
            }
            tileScroll.UpdateLayout();
            var pt = root.TranslatePoint(p, tileScroll);
            if (pressTile != null) DragTileTo(pt);
            else DragGroupTo(pt);
        }

        Rect BoundsIn(FrameworkElement el, Visual ancestor)
        {
            try { return el.TransformToAncestor(ancestor).TransformBounds(new Rect(el.RenderSize)); }
            catch { return Rect.Empty; }
        }

        void DragTileTo(Point pt)
        {
            var t = pressTile;
            var current = preview.FirstOrDefault(x => x.Tiles.Contains(t));
            foreach (var gv in groupViews)
                foreach (var tv in gv.Tiles)
                    if (tv.T == t && BoundsIn(tv.El, tileScroll).Contains(pt)) return;

            GroupView inside = null; int gapIndex = -1;
            for (int i = 0; i < groupViews.Count; i++)
            {
                var r = BoundsIn(groupViews[i].Panel, tileScroll);
                if (pt.X >= r.Left - 20 && pt.X <= r.Right + 20) { inside = groupViews[i]; break; }
                if (pt.X < r.Left - 20) { gapIndex = i; break; }
            }
            if (inside == null && gapIndex < 0) gapIndex = groupViews.Count;

            if (inside != null)
            {
                var others = inside.Tiles.Where(x => x.T != t).ToList();
                if (others.Count == 0) return;
                TileView nearest = null; double best = double.MaxValue; Rect nr = Rect.Empty;
                foreach (var tv in others)
                {
                    var r = BoundsIn(tv.El, tileScroll);
                    double dx = Math.Max(0, Math.Max(r.Left - pt.X, pt.X - r.Right)), dy = Math.Max(0, Math.Max(r.Top - pt.Y, pt.Y - r.Bottom));
                    double d = dx * dx + dy * dy;
                    if (d < best) { best = d; nearest = tv; nr = r; }
                }
                double cx = nr.Left + nr.Width / 2, cy = nr.Top + nr.Height / 2;
                bool after = (pt.X - cx) / nr.Width + (pt.Y - cy) / nr.Height > 0;
                var target = inside.G;
                var list = target.Tiles.Where(x => x != t).ToList();
                int idx = list.IndexOf(nearest.T) + (after ? 1 : 0);
                if (current == target && target.Tiles.IndexOf(t) == idx) return;
                if (current != null) current.Tiles.Remove(t);
                if (idx > target.Tiles.Count) idx = target.Tiles.Count;
                target.Tiles.Insert(idx, t);
            }
            else
            {
                if (current != null && current.Tiles.Count == 1)
                {
                    int ci = preview.IndexOf(current);
                    if (ci == gapIndex || ci == gapIndex - 1) return;
                }
                if (current != null) current.Tiles.Remove(t);
                var ng = new GroupInfo();
                ng.Tiles.Add(t);
                preview.Insert(Math.Min(gapIndex, preview.Count), ng);
            }
            preview.RemoveAll(x => x.Tiles.Count == 0);
            Render(preview, t, null);
        }

        void DragGroupTo(Point pt)
        {
            var dragged = groupViews.FirstOrDefault(x => x.Panel.Opacity < 0.5);
            if (dragged == null) return;
            int idx = 0;
            foreach (var gv in groupViews)
            {
                if (gv == dragged) continue;
                var r = BoundsIn(gv.Panel, tileScroll);
                if (pt.X > r.Left + r.Width / 2) idx++;
            }
            int cur = preview.IndexOf(dragged.G);
            if (cur == idx) return;
            preview.RemoveAt(cur);
            preview.Insert(idx, dragged.G);
            Render(preview, null, dragged.G);
        }

        void EdgeScrollTick()
        {
            if (!dragging) { edgeScroll.Stop(); return; }
            double speed = 0;
            if (lastMouse.X < 70) speed = -(70 - lastMouse.X) / 2.5;
            else if (lastMouse.X > VW - 70) speed = (lastMouse.X - (VW - 70)) / 2.5;
            if (speed == 0) return;
            tileSmooth.Jump(tileScroll.HorizontalOffset + speed);
            UpdateDrag(lastMouse);
        }

        void EndDrag(bool commit)
        {
            if (!dragging) return;
            dragging = false;
            edgeScroll.Stop();
            if (ghost != null) { overlay.Children.Remove(ghost); ghost = null; }
            if (commit && preview != null)
            {
                preview.RemoveAll(x => x.Tiles.Count == 0);
                config.Groups = preview;
                Save();
            }
            preview = null;
            pressTile = null; pressGroup = null; pressEl = null;
            if (IsMouseCaptured) ReleaseMouseCapture();
            RebuildTiles();
        }

