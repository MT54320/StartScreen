    // Eased horizontal scrolling for the mouse wheel.
    class SmoothScroll
    {
        readonly ScrollViewer sv;
        double target, current;
        bool running;
        public Func<bool> Enabled = () => true;

        public SmoothScroll(ScrollViewer s) { sv = s; }

        public void Wheel(double delta) { To((running ? target : sv.HorizontalOffset) - delta); }

        public void To(double x)
        {
            x = Math.Max(0, Math.Min(sv.ScrollableWidth, x));
            if (!Enabled()) { Jump(x); return; }
            if (!running) current = sv.HorizontalOffset;
            target = x;
            if (!running) { running = true; CompositionTarget.Rendering += Tick; }
        }

        public void Jump(double x) { Stop(); sv.ScrollToHorizontalOffset(x); }

        void Stop() { if (!running) return; running = false; CompositionTarget.Rendering -= Tick; }

        void Tick(object s, EventArgs e)
        {
            double d = target - current;
            if (Math.Abs(d) < 0.5) { sv.ScrollToHorizontalOffset(target); Stop(); return; }
            current += d * 0.16;
            sv.ScrollToHorizontalOffset(current);
        }
    }

