                t.Stop();
                string path = CaptureScreen();
                if (path != null) ShowShareWindow(path);
            };
            t.Start();
        }

        static string CaptureScreen()
        {
            try
            {
                var b = System.Windows.Forms.Screen.PrimaryScreen.Bounds;
                using (var bmp = new System.Drawing.Bitmap(b.Width, b.Height))
                {
                    using (var g = System.Drawing.Graphics.FromImage(bmp)) g.CopyFromScreen(b.Left, b.Top, 0, 0, b.Size);
                    string dir = Path.Combine(Path.GetTempPath(), "StartScreen8");
                    Directory.CreateDirectory(dir);
                    foreach (var old in Directory.GetFiles(dir, "Screenshot *.png"))
                        try { if (File.GetCreationTime(old) < DateTime.Now.AddDays(-1)) File.Delete(old); } catch { }
                    string path = Path.Combine(dir, "Screenshot " + DateTime.Now.ToString("yyyy-MM-dd HH.mm.ss") + ".png");
                    bmp.Save(path, System.Drawing.Imaging.ImageFormat.Png);
                    return path;
                }
            }
            catch (Exception ex) { App.Log(ex); return null; }
        }

        static readonly List<object> shareHandlers = new List<object>();

        static void ShowShareWindow(string path)
        {
            Window host = null;
            try
            {
                var op = global::Windows.Storage.StorageFile.GetFileFromPathAsync(path);
                var sw = Stopwatch.StartNew();
                while (op.Status == global::Windows.Foundation.AsyncStatus.Started && sw.ElapsedMilliseconds < 5000) Thread.Sleep(5);
                if (op.Status != global::Windows.Foundation.AsyncStatus.Completed) throw new InvalidOperationException("Couldn't open the screenshot file.");
                var file = op.GetResults();

                // the Share window needs a window of ours to belong to: a 1x1 invisible one in the middle of the screen
                host = new Window
                {
                    WindowStyle = WindowStyle.None, AllowsTransparency = true, Background = Brushes.Transparent, ShowInTaskbar = false,
                    Topmost = true, ResizeMode = ResizeMode.NoResize, Width = 1, Height = 1,
                    Left = SystemParameters.WorkArea.Left + SystemParameters.WorkArea.Width / 2, Top = SystemParameters.WorkArea.Top + SystemParameters.WorkArea.Height / 2
                };
                host.Show();
                host.Activate();
                var hwnd = new WindowInteropHelper(host).Handle;

                var interop = (Native.IDataTransferManagerInterop)System.Runtime.InteropServices.WindowsRuntime.WindowsRuntimeMarshal.GetActivationFactory(typeof(global::Windows.ApplicationModel.DataTransfer.DataTransferManager));
                Guid iid = new Guid("a5caee9b-8708-49d1-8d36-67d25a8da00c");
                object o;
                int hr = interop.GetForWindow(hwnd, ref iid, out o);
                if (hr != 0) Marshal.ThrowExceptionForHR(hr);
                var dtm = (global::Windows.ApplicationModel.DataTransfer.DataTransferManager)o;
                var handler = new global::Windows.Foundation.TypedEventHandler<global::Windows.ApplicationModel.DataTransfer.DataTransferManager, global::Windows.ApplicationModel.DataTransfer.DataRequestedEventArgs>((sender, args) =>
                {
                    var d = args.Request.Data;
                    d.Properties.Title = "Screenshot";
                    d.Properties.Description = Path.GetFileName(path);
                    d.SetStorageItems(new List<global::Windows.Storage.IStorageItem> { file });
                    d.SetBitmap(global::Windows.Storage.Streams.RandomAccessStreamReference.CreateFromFile(file));
                });
                shareHandlers.Add(handler); // keep it alive while the Share window is open
                dtm.DataRequested += handler;
                hr = interop.ShowShareUIForWindow(hwnd);
                if (hr != 0) Marshal.ThrowExceptionForHR(hr);

                var h = host;
                var t = new DispatcherTimer { Interval = TimeSpan.FromMinutes(3) };
                t.Tick += (s, e) => { t.Stop(); h.Close(); };
                t.Start();
            }
            catch (Exception ex)
            {
                App.Log(ex);
                if (host != null) host.Close();
                // fall back to showing the screenshot file so it can still be shared by hand
                try { Process.Start("explorer.exe", "/select,\"" + path + "\""); } catch { }
            }
        }

