        // Icon-font glyphs aren't drawn centred in their box (a speaker with fewer sound waves sits left of
        // centre). Render the glyph, find where the ink really is, and nudge it onto the box centre.
        static void CenterInk(TextBlock tb)
        {
            try
            {
                var tt = tb.RenderTransform as TranslateTransform;
                if (tt == null || string.IsNullOrEmpty(tb.Text)) return;
                var probe = new TextBlock { Text = tb.Text, FontFamily = tb.FontFamily, FontSize = tb.FontSize, Foreground = Brushes.White };
                probe.Measure(new Size(double.PositiveInfinity, double.PositiveInfinity));
                probe.Arrange(new Rect(probe.DesiredSize));
                probe.UpdateLayout();
                const int S = 4;
                int w = Math.Max(1, (int)Math.Ceiling(probe.DesiredSize.Width * S)), h = Math.Max(1, (int)Math.Ceiling(probe.DesiredSize.Height * S));
                var rtb = new RenderTargetBitmap(w, h, 96 * S, 96 * S, PixelFormats.Pbgra32);
                rtb.Render(probe);
                var px = new byte[w * h * 4];
                rtb.CopyPixels(px, w * 4, 0);
                int min = w, max = -1;
                for (int y = 0; y < h; y++)
                    for (int x = 0; x < w; x++)
                        if (px[(y * w + x) * 4 + 3] > 24) { if (x < min) min = x; if (x > max) max = x; }
                if (max < 0) return;
                double inkCentre = (min + max + 1) / 2.0 / S;
                tt.X = Math.Round(probe.DesiredSize.Width / 2 - inkCentre, 1);
            }
            catch (Exception ex) { App.Log(ex); }
        }

