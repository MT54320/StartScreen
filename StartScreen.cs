    // Intercepts a lone press of the Windows key. Win+<anything> combos still go to Windows.
    class WinKeyHook
    {
        Native.LowLevelKeyboardProc proc;
        IntPtr hook = IntPtr.Zero;
        bool winDown, combo;
        public bool Enabled = true;
        public event Action WinPressed;

        public void Install()
        {
            proc = Callback;
            using (var p = Process.GetCurrentProcess())
            using (var m = p.MainModule)
                hook = Native.SetWindowsHookEx(13 /*WH_KEYBOARD_LL*/, proc, Native.GetModuleHandle(m.ModuleName), 0);
        }

        public void Uninstall()
        {
            if (hook != IntPtr.Zero) Native.UnhookWindowsHookEx(hook);
            hook = IntPtr.Zero;
        }

        IntPtr Callback(int n, IntPtr w, IntPtr l)
        {
            if (n >= 0)
            {
                var k = (Native.KBDLLHOOKSTRUCT)Marshal.PtrToStructure(l, typeof(Native.KBDLLHOOKSTRUCT));
                int msg = w.ToInt32();
                bool down = msg == 0x100 || msg == 0x104;
                bool up = msg == 0x101 || msg == 0x105;
                bool injected = (k.flags & 0x10) != 0;
                if (!injected)
                {
                    bool isWin = k.vkCode == 0x5B || k.vkCode == 0x5C;
                    if (isWin)
                    {
                        if (down) { if (!winDown) { winDown = true; combo = false; } }
                        else if (up)
                        {
                            bool alone = winDown && !combo;
                            winDown = false;
                            if (alone && Enabled)
                            {
                                SendMask();
                                var h = WinPressed;
                                if (h != null) h();
                            }
                        }
                    }
                    else if (down && winDown) combo = true;
                }
            }
            return Native.CallNextHookEx(hook, n, w, l);
        }

        static void SendMask()
        {
            var inputs = new Native.INPUT[2];
            inputs[0].type = 1; inputs[0].u.ki.wVk = 0xE8;
            inputs[1].type = 1; inputs[1].u.ki.wVk = 0xE8; inputs[1].u.ki.dwFlags = 2;
            Native.SendInput(2, inputs, Marshal.SizeOf(typeof(Native.INPUT)));
        }
    }

    // Opens our Start screen when the physical taskbar Start button is left-clicked.
    // A low-level mouse hook (the same mechanism as the Win-key hook) swallows the click so the
    // Windows 11 Start menu never opens. The button's screen rectangle is refreshed off-thread with
    // UI Automation, keeping the hook callback to a cheap point-in-rectangle test. Interception is
    // paused while our Start screen is already open (Open == true) so clicks land on our own UI.
    class StartButtonHook
    {
        Native.LowLevelKeyboardProc proc;   // identical (int,IntPtr,IntPtr)->IntPtr signature
        IntPtr hook = IntPtr.Zero;
        Timer timer;
        volatile int rx, ry, rw, rh;        // cached Start button rect, screen pixels
        bool pressedOnStart;
        public volatile bool Open;          // our Start screen is currently showing
        public bool Enabled = true;
        public event Action Clicked;

        public void Install()
        {
            ThreadPool.QueueUserWorkItem(_ => { try { RefreshRect(); } catch { } });
            timer = new Timer(_ => { try { RefreshRect(); } catch { } }, null, 2500, 2500);
            proc = Callback;
            using (var p = Process.GetCurrentProcess())
            using (var m = p.MainModule)
                hook = Native.SetWindowsHookEx(14 /*WH_MOUSE_LL*/, proc, Native.GetModuleHandle(m.ModuleName), 0);
        }

        public void Uninstall()
        {
            if (timer != null) { timer.Dispose(); timer = null; }
            if (hook != IntPtr.Zero) Native.UnhookWindowsHookEx(hook);
            hook = IntPtr.Zero;
        }

        void RefreshRect()
        {
            var root = System.Windows.Automation.AutomationElement.RootElement;
            if (root == null) return;
            var tray = root.FindFirst(System.Windows.Automation.TreeScope.Children,
                new System.Windows.Automation.PropertyCondition(System.Windows.Automation.AutomationElement.ClassNameProperty, "Shell_TrayWnd"));
            if (tray == null) return;
            var start = tray.FindFirst(System.Windows.Automation.TreeScope.Descendants,
                new System.Windows.Automation.PropertyCondition(System.Windows.Automation.AutomationElement.NameProperty, "Start"));
            if (start == null) return;
            var r = start.Current.BoundingRectangle;
            if (r.Width < 1 || r.Width > 400 || r.Height < 1 || r.Height > 400) return;   // sanity
            rx = (int)r.X; ry = (int)r.Y; rw = (int)r.Width; rh = (int)r.Height;
        }

        IntPtr Callback(int n, IntPtr w, IntPtr l)
        {
            if (n >= 0 && Enabled && !Open && rw > 0)
            {
                int msg = w.ToInt32();
                if (msg == 0x201 || msg == 0x202) // WM_LBUTTONDOWN / WM_LBUTTONUP
                {
                    var ms = (Native.MSLLHOOKSTRUCT)Marshal.PtrToStructure(l, typeof(Native.MSLLHOOKSTRUCT));
                    bool injected = (ms.flags & 0x01) != 0; // LLMHF_INJECTED
                    if (!injected)
                    {
                        bool over = ms.pt.x >= rx && ms.pt.x < rx + rw && ms.pt.y >= ry && ms.pt.y < ry + rh;
                        if (msg == 0x201)
                        {
                            if (over)
                            {
                                pressedOnStart = true;
                                var h = Clicked; if (h != null) h();
                                return (IntPtr)1;   // swallow the press so Windows' own Start never opens
                            }
                            pressedOnStart = false;
                        }
                        else if (pressedOnStart)   // matching release
                        {
                            pressedOnStart = false;
                            return (IntPtr)1;
                        }
                    }
                }
            }
            return Native.CallNextHookEx(hook, n, w, l);
        }
    }

