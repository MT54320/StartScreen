        // ---- Share (like the 8.1 Share charm): screenshot what's behind Start and open the Windows Share window

        void Share()
        {
            CloseBar(true);
            ClosePanel(true);
            root.BeginAnimation(OpacityProperty, null);
            hiding = false;
            Hide();
            // give the desktop a moment to repaint before capturing it
            var t = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(300) };
