        static void SetRunAtSignIn(bool on)
        {
            using (var k = Registry.CurrentUser.CreateSubKey(RunKey))
            {
                if (on) k.SetValue(RunName, "\"" + Process.GetCurrentProcess().MainModule.FileName + "\" /background");
                else k.DeleteValue(RunName, false);
            }
        }

