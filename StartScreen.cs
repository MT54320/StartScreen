        // Moving between Settings, Tiles and Help: the new menu slides in from the side (from the right when you go
        // deeper, from the left when you go back) while the old one slides away and fades, instead of swapping instantly.
        void GoPanel(string kind)
        {
            bool forward = kind != "settings";
            UIElement old = sidePanel.Child;
            ImageBrush snap = null;
            double pw = sidePanel.ActualWidth, ph = sidePanel.ActualHeight;
            if (Anim && panelOpen && old != null && pw > 0 && ph > 0)
            {
                try
                {
                    double dpi = 1;
                    var src = PresentationSource.FromVisual(this);
                    if (src != null && src.CompositionTarget != null) dpi = src.CompositionTarget.TransformToDevice.M11 * uiScale.ScaleX;
                    var rtb = new RenderTargetBitmap(Math.Max(1, (int)(pw * dpi)), Math.Max(1, (int)(ph * dpi)), 96 * dpi, 96 * dpi, PixelFormats.Pbgra32);
                    rtb.Render(sidePanel);        // includes the panel colour, so the old page looks exactly as it did
                    snap = new ImageBrush(rtb);
                }
                catch (Exception ex) { App.Log(ex); snap = null; }
            }

            panelKind = kind;
            FillPanel();
            if (snap == null) return;

            var neu = sidePanel.Child as FrameworkElement;
            if (neu == null) return;
            sidePanel.Child = null;
            var host = new Grid { ClipToBounds = true };
            var ghost = new Border { Background = snap, IsHitTestVisible = false, RenderTransform = new TranslateTransform() };
            neu.RenderTransform = new TranslateTransform();
            host.Children.Add(ghost);          // old page underneath, new page on top
            host.Children.Add(neu);
            sidePanel.Child = host;

            var ease = new CubicEase { EasingMode = EasingMode.EaseOut };
            var dur = TimeSpan.FromMilliseconds(320);
            double from = forward ? pw : -pw;
            ((TranslateTransform)neu.RenderTransform).BeginAnimation(TranslateTransform.XProperty, new DoubleAnimation(from, 0, dur) { EasingFunction = ease });
            neu.BeginAnimation(OpacityProperty, new DoubleAnimation(0.2, 1, TimeSpan.FromMilliseconds(260)));
            var gt = (TranslateTransform)ghost.RenderTransform;
            var outAnim = new DoubleAnimation(0, forward ? -pw * 0.35 : pw * 0.35, dur) { EasingFunction = ease };
            outAnim.Completed += (s, e) =>
            {
                // hand the new page back to the panel so later refreshes behave as before
                if (sidePanel.Child == host && host.Children.Contains(neu))
                {
                    host.Children.Remove(neu);
                    neu.BeginAnimation(OpacityProperty, null);
                    neu.RenderTransform = null;
                    sidePanel.Child = neu;
                }
            };
            gt.BeginAnimation(TranslateTransform.XProperty, outAnim);
            ghost.BeginAnimation(OpacityProperty, new DoubleAnimation(1, 0, TimeSpan.FromMilliseconds(190)));
        }

