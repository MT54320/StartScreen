        // ---------------- all apps / search

        void RebuildApps()
        {
            if (appsWrap == null) return;
            appsWrap.Children.Clear();
            results = new List<AppEntry>();
            resultViews = new List<Border>();
            selected = -1;
            string q = searchBox.Text.Trim();
            if (q.Length == 0)
            {
                string letter = null;
                foreach (var a in apps)
                {
                    char ch = char.ToUpper(a.Name[0]);
                    string l = char.IsLetter(ch) ? ch.ToString() : "#";
                    if (l != letter)
                    {
                        letter = l;
                        appsWrap.Children.Add(new TextBlock { Text = l, FontFamily = Light, FontSize = 30, Width = 280, Height = 50, Margin = new Thickness(0, 0, 34, 4), Padding = new Thickness(2, 4, 0, 0) });
                    }
                    appsWrap.Children.Add(MakeAppItem(a, -1));
                }
                if (apps.Count == 0)
                    appsWrap.Children.Add(new TextBlock { Text = appsLoaded ? "No apps found." : "Loading apps…", FontFamily = Light, FontSize = 22 });
                return;
            }

            results = apps
                .Select(a => new { a, score = Score(a.Name, q) })
                .Where(x => x.score > 0)
                .OrderByDescending(x => x.score).ThenBy(x => x.a.Name)
                .Select(x => x.a).ToList();
            appsWrap.Children.Add(new TextBlock
            {
                Text = results.Count == 0 ? "No apps match “" + q + "”" : results.Count + (results.Count == 1 ? " result" : " results") + " for “" + q + "”",
                FontFamily = Light, FontSize = 22, Width = 280, Height = 50, Margin = new Thickness(0, 0, 34, 4), TextTrimming = TextTrimming.CharacterEllipsis
            });
            for (int i = 0; i < results.Count; i++) appsWrap.Children.Add(MakeAppItem(results[i], i));
            Select(results.Count > 0 ? 0 : -1);
        }

        void Select(int i)
        {
            if (results.Count == 0) { selected = -1; return; }
            i = Math.Max(0, Math.Min(results.Count - 1, i));
            selected = i;
            for (int k = 0; k < resultViews.Count; k++)
                resultViews[k].Background = k == i ? Colorx.Brush(0x44, 255, 255, 255) : Brushes.Transparent;
            if (i < resultViews.Count) resultViews[i].BringIntoView();
        }

        static int Score(string name, string q)
        {
            if (name.StartsWith(q, StringComparison.CurrentCultureIgnoreCase)) return 4;
            foreach (var w in name.Split(' ', '-', '(', '.', '_'))
                if (w.StartsWith(q, StringComparison.CurrentCultureIgnoreCase)) return 3;
            if (name.IndexOf(q, StringComparison.CurrentCultureIgnoreCase) >= 0) return 2;
            var initials = new string(name.Split(new[] { ' ', '-' }, StringSplitOptions.RemoveEmptyEntries).Select(w => w[0]).ToArray());
            return q.Length > 1 && initials.StartsWith(q, StringComparison.CurrentCultureIgnoreCase) ? 1 : 0;
        }

