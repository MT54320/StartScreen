        FrameworkElement ShadeGrid(int rows, Func<int, Color> color, int current, Action<int> pick, out Action<Func<int, Color>> recolor)
        {
            var g = new UniformGrid { Columns = 6, Rows = rows, Width = 300, HorizontalAlignment = HorizontalAlignment.Left };
