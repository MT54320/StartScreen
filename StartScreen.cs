    static class AppCatalog
    {
        public static List<AppEntry> Enumerate()
        {
            var list = new List<AppEntry>();
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            Type t = Type.GetTypeFromProgID("Shell.Application");
            dynamic shell = Activator.CreateInstance(t);
            try
            {
                dynamic folder = shell.NameSpace("shell:::{4234d49b-0245-4df3-b780-3893943456e1}");
                if (folder == null) return list;
                foreach (dynamic item in folder.Items())
                {
                    string name = item.Name;
                    string id = item.Path;
                    if (string.IsNullOrEmpty(name) || string.IsNullOrEmpty(id)) continue;
                    if (name.IndexOf("uninstall", StringComparison.OrdinalIgnoreCase) >= 0) continue;
                    if (!seen.Add(id)) continue;
                    list.Add(new AppEntry { Name = name, Id = id });
                }
            }
            finally { Marshal.ReleaseComObject(shell); }
            list.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));
            return list;
        }

        // Last-resort icon via the shell's image factory.
        public static BitmapSource FactoryIcon(string id, int size)
        {
            Guid iid = new Guid("bcc18b79-ba16-442f-80c4-8a59c30c463b");
            Native.IShellItemImageFactory f;
            int hr = Native.SHCreateItemFromParsingName("shell:AppsFolder\\" + id, IntPtr.Zero, ref iid, out f);
            if (hr != 0 || f == null) return null;
            try
            {
                IntPtr hbm;
                Native.SIZE sz; sz.cx = size; sz.cy = size;
                hr = f.GetImage(sz, 0x4 /*ICONONLY*/, out hbm);
                if (hr != 0 || hbm == IntPtr.Zero) return null;
                try
                {
                    var bm = new Native.BITMAP();
                    Native.GetObject(hbm, Marshal.SizeOf(typeof(Native.BITMAP)), ref bm);
                    int w = bm.bmWidth, h = bm.bmHeight;
                    if (w <= 0 || h <= 0) return null;
                    var bi = new Native.BITMAPINFOHEADER();
                    bi.biSize = 40; bi.biWidth = w; bi.biHeight = -h; bi.biPlanes = 1; bi.biBitCount = 32;
                    byte[] px = new byte[w * h * 4];
                    IntPtr dc = Native.GetDC(IntPtr.Zero);
                    try { Native.GetDIBits(dc, hbm, 0, (uint)h, px, ref bi, 0); }
                    finally { Native.ReleaseDC(IntPtr.Zero, dc); }
                    bool anyAlpha = false;
                    for (int i = 3; i < px.Length; i += 4) if (px[i] != 0) { anyAlpha = true; break; }
                    if (!anyAlpha) for (int i = 3; i < px.Length; i += 4) px[i] = 255;
                    var src = BitmapSource.Create(w, h, 96, 96, PixelFormats.Pbgra32, null, px, w * 4);
                    src.Freeze();
                    return src;
                }
                finally { Native.DeleteObject(hbm); }
            }
            finally { Marshal.ReleaseComObject(f); }
        }

        public static bool DominantColor(byte[] px, out Color c)
        {
            c = Colors.Black;
            if (px == null) return false;
            double r = 0, g = 0, b = 0, ws = 0;
            for (int i = 0; i < px.Length; i += 4)
            {
                int a = px[i + 3];
                if (a < 160) continue;
                double B = Math.Min(255, px[i] * 255.0 / a), G = Math.Min(255, px[i + 1] * 255.0 / a), R = Math.Min(255, px[i + 2] * 255.0 / a);
                double mx = Math.Max(R, Math.Max(G, B)), mn = Math.Min(R, Math.Min(G, B));
                double sat = mx <= 0 ? 0 : (mx - mn) / mx;
                double wgt = 0.03 + sat * sat * (mx / 255.0);
                r += R * wgt; g += G * wgt; b += B * wgt; ws += wgt;
            }
            if (ws <= 0) return false;
            double hh, s, v;
            Colorx.ToHsv(r / ws, g / ws, b / ws, out hh, out s, out v);
            if (s < 0.22) return false;
            s = Math.Max(0.55, Math.Min(0.85, s));
            v = Math.Max(0.45, Math.Min(0.68, v));
            c = Colorx.FromHsv(hh, s, v);
            return true;
        }

        static readonly string[][] KnownFolders = {
            new[] { "{6D809377-6AF0-444B-8957-A3773F02200E}", Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles) },
            new[] { "{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}", Environment.GetFolderPath(Environment.SpecialFolder.ProgramFilesX86) },
            new[] { "{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}", Environment.GetFolderPath(Environment.SpecialFolder.System) },
            new[] { "{F38BF404-1D43-42F2-9305-67DE0B28FC23}", Environment.GetFolderPath(Environment.SpecialFolder.Windows) },
        };

        public static string ResolvePath(string id)
        {
            if (string.IsNullOrEmpty(id)) return null;
            try
            {
                if (id.IndexOf('\\') >= 0 && File.Exists(id)) return id;
                foreach (var kf in KnownFolders)
                    if (id.StartsWith(kf[0], StringComparison.OrdinalIgnoreCase))
                    {
                        string p = kf[1] + id.Substring(kf[0].Length);
                        if (File.Exists(p)) return p;
                    }
            }
            catch { }
            return null;
        }

        public static void Launch(string id, bool admin)
        {
            try
            {
                string path = ResolvePath(id);
                if (admin && path != null)
                {
                    Process.Start(new ProcessStartInfo(path) { UseShellExecute = true, Verb = "runas" });
                    return;
                }
                Process.Start(new ProcessStartInfo("explorer.exe", "\"shell:AppsFolder\\" + id + "\"") { UseShellExecute = true });
            }
            catch (Exception ex) { App.Log(ex); }
        }

        // Start menu shortcuts by name, so "Open file location" goes to the shortcut like the real Start menu does.
        static Dictionary<string, string> shortcuts;
        public static void ResetShortcuts() { shortcuts = null; }

        static void Walk(string dir, Dictionary<string, string> map, int depth)
        {
            if (depth > 6) return;
            try
            {
                foreach (var f in Directory.GetFiles(dir))
                {
                    var ext = Path.GetExtension(f).ToLowerInvariant();
                    if (ext != ".lnk" && ext != ".url" && ext != ".appref-ms") continue;
                    var n = Path.GetFileNameWithoutExtension(f);
                    if (!map.ContainsKey(n)) map[n] = f;
                }
                foreach (var d in Directory.GetDirectories(dir)) Walk(d, map, depth + 1);
            }
            catch { }
        }

        static string FindShortcut(string name)
        {
            if (string.IsNullOrEmpty(name)) return null;
            if (shortcuts == null)
            {
                var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                foreach (var root in new[] { Environment.GetFolderPath(Environment.SpecialFolder.StartMenu), Environment.GetFolderPath(Environment.SpecialFolder.CommonStartMenu) })
                    if (!string.IsNullOrEmpty(root)) Walk(Path.Combine(root, "Programs"), map, 0);
                shortcuts = map;
            }
            string p;
            return shortcuts.TryGetValue(name, out p) ? p : null;
        }

        public static string LocationOf(string id, string name)
        {
            return FindShortcut(name) ?? ResolvePath(id);
        }

        public static void OpenLocation(string id, string name)
        {
            string p = LocationOf(id, name);
            if (p == null) return;
            try { Process.Start("explorer.exe", "/select,\"" + p + "\""); } catch (Exception ex) { App.Log(ex); }
        }

        public static bool IsStoreApp(string id)
        {
            return id != null && id.IndexOf('!') > 0 && id.IndexOf('\\') < 0;
        }

        public static string ShortcutOf(string name) { return FindShortcut(name); }

        // The program a shortcut points at.
        public static string ShortcutTarget(string lnk)
        {
            if (lnk == null || !lnk.EndsWith(".lnk", StringComparison.OrdinalIgnoreCase)) return null;
            try
            {
                dynamic sh = Activator.CreateInstance(Type.GetTypeFromProgID("WScript.Shell"));
                try
                {
                    dynamic l = sh.CreateShortcut(lnk);
                    string t = l.TargetPath;
                    return string.IsNullOrEmpty(t) ? null : t;
                }
                finally { Marshal.ReleaseComObject(sh); }
            }
            catch { return null; }
        }

        public static string TargetOf(string id, string name)
        {
            return ResolvePath(id) ?? ShortcutTarget(FindShortcut(name));
        }
    }

    // ---------------------------------------------------------- uninstall

    // Works out how to really remove an app, then does it:
    //  - Store apps: Remove-AppxPackage for you, then (with admin) for every user plus the provisioned copy
    //  - Desktop programs: their own uninstaller from the registry, run silently (admin prompt when it's a per-machine install)
    //  - Steam games: hands over to Steam's uninstall
    //  - Nothing found: offers to delete the Start shortcut instead
    public class UninstallPlan
    {
        public string Kind;           // store | program | steam | shortcut | none
        public string Title;          // what will actually be removed
        public string Family, Exe, Args, SteamId, Shortcut;
        public bool Elevate;
        public RegistryHive Hive;
        public RegistryView View;
        public string Key;
    }

    static class Uninstaller
    {
        const string UninstallPath = @"SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall";

        class Entry { public RegistryHive Hive; public RegistryView View; public string Key, Name, Quiet, Cmd, Location, Icon; public bool Inno; }

        static List<Entry> Entries()
        {
            var list = new List<Entry>();
            var sources = new[]
            {
                Tuple.Create(RegistryHive.LocalMachine, RegistryView.Registry64),
                Tuple.Create(RegistryHive.LocalMachine, RegistryView.Registry32),
                Tuple.Create(RegistryHive.CurrentUser, RegistryView.Registry64),
            };
            foreach (var src in sources)
            {
                try
                {
                    using (var bk = RegistryKey.OpenBaseKey(src.Item1, src.Item2))
                    using (var k = bk.OpenSubKey(UninstallPath))
                    {
                        if (k == null) continue;
                        foreach (var sub in k.GetSubKeyNames())
                            using (var e = k.OpenSubKey(sub))
                            {
                                if (e == null) continue;
                                var name = e.GetValue("DisplayName") as string;
                                var cmd = e.GetValue("UninstallString") as string;
                                if (string.IsNullOrEmpty(name) || string.IsNullOrEmpty(cmd)) continue;
                                list.Add(new Entry
                                {
                                    Hive = src.Item1, View = src.Item2, Key = sub, Name = name, Cmd = cmd,
                                    Quiet = e.GetValue("QuietUninstallString") as string,
                                    Location = e.GetValue("InstallLocation") as string,
                                    Icon = e.GetValue("DisplayIcon") as string,
                                    Inno = e.GetValue("Inno Setup: App Path") != null
                                });
                            }
                    }
                }
                catch { }
            }
            return list;
        }

        static string Norm(string s) { return new string((s ?? "").ToLowerInvariant().Where(char.IsLetterOrDigit).ToArray()); }

        static readonly string WinDir = Environment.GetFolderPath(Environment.SpecialFolder.Windows).TrimEnd('\\').ToLowerInvariant();
        static bool InWindows(string path)
        {
            if (string.IsNullOrEmpty(path)) return false;
            var p = path.Trim('"').ToLowerInvariant();
            return p == WinDir || p.StartsWith(WinDir + "\\");
        }

        static string CleanPath(string p)
        {
            if (string.IsNullOrEmpty(p)) return "";
            p = p.Trim();
            int comma = p.LastIndexOf(',');
            if (comma > 0 && p.Substring(comma + 1).Trim().All(c => char.IsDigit(c) || c == '-')) p = p.Substring(0, comma);
            return p.Trim().Trim('"').TrimEnd('\\').ToLowerInvariant();
        }

        // folders that are far too broad to count as "this app's folder"
        static readonly HashSet<string> Broad = new HashSet<string>(new[]
        {
            Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles), Environment.GetFolderPath(Environment.SpecialFolder.ProgramFilesX86),
            Environment.GetFolderPath(Environment.SpecialFolder.Windows), Environment.GetFolderPath(Environment.SpecialFolder.System),
            Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
            Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Programs"),
            Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData),
        }.Where(x => !string.IsNullOrEmpty(x)).Select(x => x.TrimEnd('\\').ToLowerInvariant()), StringComparer.OrdinalIgnoreCase);

        static Entry Find(string name, string exe)
        {
            string exeN = null;
            try { if (!string.IsNullOrEmpty(exe)) exeN = Path.GetFullPath(exe).ToLowerInvariant(); } catch { }
            if (exeN != null && InWindows(exeN)) exeN = null; // never match Windows' own files by folder
            string exeDir = exeN != null ? Path.GetDirectoryName(exeN) : null;
            string a = Norm(name);
            Entry best = null; int bestScore = 0;
            foreach (var e in Entries())
            {
                int sc = 0;
                bool steamGame = e.Cmd.IndexOf("steam://", StringComparison.OrdinalIgnoreCase) >= 0;
                if (exeN != null && !steamGame)
                {
                    var loc = CleanPath(e.Location);
                    if (loc.Length > 3 && !Broad.Contains(loc) && exeN.StartsWith(loc + "\\")) sc = Math.Max(sc, 100);
                    if (CleanPath(e.Icon) == exeN) sc = Math.Max(sc, 95);
                    string uexe, uargs;
                    Split(e.Cmd, out uexe, out uargs);
                    try
                    {
                        var udir = Path.GetDirectoryName(uexe);
                        if (!string.IsNullOrEmpty(udir) && !InWindows(udir) && !Broad.Contains(udir.TrimEnd('\\')) && string.Equals(udir.TrimEnd('\\'), exeDir, StringComparison.OrdinalIgnoreCase)) sc = Math.Max(sc, 90);
                    }
                    catch { }
                }
                string b = Norm(e.Name);
                int nameScore = 0;
                if (a.Length > 0)
                {
                    if (a == b) nameScore = 85;
                    else if (a.Length >= 4 && b.Length >= 4 && (b.StartsWith(a) || a.StartsWith(b))) nameScore = 60;
                    else if (a.Length >= 5 && b.Contains(a)) nameScore = 45;
                }
                // a matching name breaks ties between entries that share a folder
                sc = Math.Max(sc, nameScore) + (nameScore >= 60 && sc >= nameScore ? 5 : 0);
                if (sc > bestScore) { bestScore = sc; best = e; }
            }
            return bestScore >= 45 ? best : null;
        }

        static void Split(string cmd, out string exe, out string args)
        {
            cmd = (cmd ?? "").Trim();
            exe = cmd; args = "";
            if (cmd.StartsWith("\""))
            {
                int end = cmd.IndexOf('"', 1);
                if (end > 0) { exe = cmd.Substring(1, end - 1); args = cmd.Substring(end + 1).Trim(); }
                return;
            }
            int i = cmd.ToLowerInvariant().IndexOf(".exe");
            if (i > 0) { exe = cmd.Substring(0, i + 4); args = cmd.Substring(i + 4).Trim(); return; }
            int sp = cmd.IndexOf(' ');
            if (sp > 0) { exe = cmd.Substring(0, sp); args = cmd.Substring(sp + 1).Trim(); }
        }

        public static UninstallPlan Make(string id, string name, string target, string shortcut)
        {
            if (AppCatalog.IsStoreApp(id))
                return new UninstallPlan { Kind = "store", Title = name, Family = id.Substring(0, id.IndexOf('!')) };

            // Windows' own tools (File Explorer, Control Panel, Command Prompt...) are left alone.
            bool systemFolder = shortcut != null && Regex.IsMatch(shortcut, @"\\(Windows Tools|Administrative Tools|System Tools|Accessibility|Windows Accessories|Windows PowerShell)\\", RegexOptions.IgnoreCase);
            bool systemName = string.Equals(name, "Control Panel", StringComparison.OrdinalIgnoreCase) && target == null;
            if ((id ?? "").StartsWith("Microsoft.Windows.", StringComparison.OrdinalIgnoreCase) || InWindows(target) || systemFolder || systemName)
                return new UninstallPlan { Kind = "system", Title = name };

            var steam = Regex.Match(id ?? "", @"^steam://rungameid/(\d+)", RegexOptions.IgnoreCase);
            if (!steam.Success && target != null) steam = Regex.Match(target, @"^steam://rungameid/(\d+)", RegexOptions.IgnoreCase);
            if (steam.Success) return new UninstallPlan { Kind = "steam", Title = name, SteamId = steam.Groups[1].Value };

            var e = Find(name, target);
            if (e != null)
            {
                bool quiet = !string.IsNullOrEmpty(e.Quiet);
                string exe, args;
                Split(quiet ? e.Quiet : e.Cmd, out exe, out args);
                if (!quiet)
                {
                    string exeName = Path.GetFileName(exe).ToLowerInvariant();
                    if (exeName.StartsWith("msiexec"))
                    {
                        args = Regex.Replace(args, @"/I(?=\s*\{)", "/X", RegexOptions.IgnoreCase) + " /qn /norestart";
                    }
                    else if (e.Inno) args += " /VERYSILENT /SUPPRESSMSGBOXES /NORESTART";
                    else if (exeName == "update.exe" && args.IndexOf("--uninstall", StringComparison.OrdinalIgnoreCase) >= 0) args += " -s";
                    else if (exeName.StartsWith("uninst")) args += " /S";
                }
                return new UninstallPlan
                {
                    Kind = "program", Title = e.Name, Exe = exe, Args = args.Trim(),
                    Elevate = e.Hive == RegistryHive.LocalMachine, Hive = e.Hive, View = e.View, Key = e.Key
                };
            }
            if (shortcut != null) return new UninstallPlan { Kind = "shortcut", Title = name, Shortcut = shortcut };
            return new UninstallPlan { Kind = "none", Title = name };
        }

        static bool KeyExists(UninstallPlan p)
        {
            try
            {
                using (var bk = RegistryKey.OpenBaseKey(p.Hive, p.View))
                using (var k = bk.OpenSubKey(UninstallPath + "\\" + p.Key))
                    return k != null;
            }
            catch { return true; }
        }

        // Runs a PowerShell script, optionally as admin. Returns the exit code, or -1223 if the admin prompt was declined.
        static int RunPowerShell(string script, bool elevated)
        {
            string enc = Convert.ToBase64String(System.Text.Encoding.Unicode.GetBytes(script));
            var psi = new ProcessStartInfo("powershell.exe", "-NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -EncodedCommand " + enc);
            if (elevated) { psi.UseShellExecute = true; psi.Verb = "runas"; psi.WindowStyle = ProcessWindowStyle.Hidden; }
            else { psi.UseShellExecute = false; psi.CreateNoWindow = true; }
            try
            {
                using (var p = Process.Start(psi))
                {
                    p.WaitForExit(300000);
                    return p.HasExited ? p.ExitCode : 1;
                }
            }
            catch (System.ComponentModel.Win32Exception ex) { if (ex.NativeErrorCode == 1223) return -1223; App.Log(ex); return 1; }
        }

        // done(result, message): result is done | cancelled | failed | handoff
        public static void Run(UninstallPlan plan, Action<string, string> done)
        {
            var th = new Thread(() =>
            {
                string res = "failed", msg = "“" + plan.Title + "” couldn't be uninstalled.";
                try
                {
                    if (plan.Kind == "store")
                    {
                        string fam = plan.Family.Replace("'", "''");
                        string find = "$p = @(Get-AppxPackage {0} | Where-Object {{ $_.PackageFamilyName -eq '" + fam + "' }}); if ($p.Count -eq 0) {{ exit 2 }}; if ($p | Where-Object {{ $_.NonRemovable }}) {{ exit 3 }}; ";
                        int code = RunPowerShell(string.Format(find, "") + "try { $p | Remove-AppxPackage -ErrorAction Stop; exit 0 } catch { exit 1 }", false);
                        if (code != 0 && code != 3)
                            code = RunPowerShell(string.Format(find, "-AllUsers") +
                                "try { $p | Remove-AppxPackage -AllUsers -ErrorAction Stop; " +
                                "Get-AppxProvisionedPackage -Online | Where-Object { $_.DisplayName -eq $p[0].Name } | Remove-AppxProvisionedPackage -Online -ErrorAction SilentlyContinue | Out-Null; exit 0 } catch { exit 1 }", true);
                        if (code == 0) { res = "done"; msg = "“" + plan.Title + "” was uninstalled."; }
                        else if (code == 3) msg = "“" + plan.Title + "” is built into Windows and can't be removed.";
                        else if (code == -1223) { res = "cancelled"; msg = "Uninstall cancelled."; }
                    }
                    else if (plan.Kind == "program")
                    {
                        var psi = new ProcessStartInfo(plan.Exe, plan.Args) { UseShellExecute = true };
                        if (plan.Elevate) psi.Verb = "runas";
                        try
                        {
                            using (var p = Process.Start(psi)) if (p != null) p.WaitForExit(15 * 60 * 1000);
                            // many uninstallers hand off to a temp copy and exit straight away, so wait for the entry to disappear
                            for (int i = 0; i < 90 && KeyExists(plan); i++) Thread.Sleep(2000);
                            if (!KeyExists(plan)) { res = "done"; msg = "“" + plan.Title + "” was uninstalled."; }
                            else msg = "The uninstaller finished, but “" + plan.Title + "” is still installed.";
                        }
                        catch (System.ComponentModel.Win32Exception ex)
                        {
                            if (ex.NativeErrorCode == 1223) { res = "cancelled"; msg = "Uninstall cancelled."; }
                            else { App.Log(ex); msg = "Couldn't start the uninstaller for “" + plan.Title + "”."; }
                        }
                    }
                    else if (plan.Kind == "steam")
                    {
                        Process.Start(new ProcessStartInfo("steam://uninstall/" + plan.SteamId) { UseShellExecute = true });
                        res = "handoff"; msg = "Finish uninstalling “" + plan.Title + "” in Steam.";
                    }
                    else if (plan.Kind == "shortcut")
                    {
                        bool ok = false;
                        try { File.Delete(plan.Shortcut); ok = !File.Exists(plan.Shortcut); }
                        catch (UnauthorizedAccessException) { }
                        if (!ok)
                        {
                            int code = RunPowerShell("Remove-Item -LiteralPath '" + plan.Shortcut.Replace("'", "''") + "' -Force -ErrorAction Stop", true);
                            ok = code == 0;
                            if (code == -1223) { res = "cancelled"; msg = "Cancelled."; }
                        }
                        if (ok) { res = "done"; msg = "Removed “" + plan.Title + "” from Start."; }
                    }
                }
                catch (Exception ex) { App.Log(ex); }
                done(res, msg);
            });
            th.IsBackground = true;
            th.Start();
        }
    }

    // ------------------------------------------------------------- icons

    // Finds the sharpest icon available for each app:
    //  - Store apps: the app's own logo files from its package (256px, transparent "unplated" versions)
    //  - Desktop apps: the 256px system icon, trimmed to the real artwork so small icons are never blown up
    static class IconLoader
    {
        [ThreadStatic] static Native.IImageList jumbo;
        static Dictionary<string, string> packageRoots;

        public static void ResetPackages() { packageRoots = null; }

        public static void Load(AppEntry a)
        {
            BitmapSource img = null;
            string bg = null;
            try { if (a.Id.IndexOf('!') > 0) img = UwpLogo(a.Id, out bg); } catch (Exception ex) { App.Log(ex); }
            if (img == null) try { img = Jumbo(a.Id); } catch (Exception ex) { App.Log(ex); }
            if (img == null) try { img = AppCatalog.FactoryIcon(a.Id, 256); } catch (Exception ex) { App.Log(ex); }
            if (img == null) return;

            byte[] px;
            img = Trim(img, out px);
            a.Icon = img;
            a.IconPx = Math.Max(img.PixelWidth, img.PixelHeight);
            Color c;
            if (bg != null && bg.StartsWith("#") && Colorx.TryParse(bg, out c)) { a.TileColor = c; a.HasColor = true; }
            else { a.HasColor = AppCatalog.DominantColor(px, out c); a.TileColor = c; }
        }

        // Crop away transparent padding so every icon is sized by its real artwork.
        static BitmapSource Trim(BitmapSource src, out byte[] pixels)
        {
            var conv = new FormatConvertedBitmap(src, PixelFormats.Pbgra32, null, 0);
            int w = conv.PixelWidth, h = conv.PixelHeight, stride = w * 4;
            var px = new byte[stride * h];
            conv.CopyPixels(px, stride, 0);
            int minX = w, minY = h, maxX = -1, maxY = -1;
            for (int y = 0; y < h; y++)
                for (int x = 0; x < w; x++)
                    if (px[y * stride + x * 4 + 3] > 12)
                    {
                        if (x < minX) minX = x; if (x > maxX) maxX = x;
                        if (y < minY) minY = y; if (y > maxY) maxY = y;
                    }
            if (maxX < 0) { pixels = px; conv.Freeze(); return conv; }
            // keep it square so icons sit centred
            int cw = maxX - minX + 1, ch = maxY - minY + 1, side = Math.Max(cw, ch);
            int cx = minX - (side - cw) / 2, cy = minY - (side - ch) / 2;
            cx = Math.Max(0, Math.Min(w - side, cx)); cy = Math.Max(0, Math.Min(h - side, cy));
            if (side > w || side > h) { pixels = px; conv.Freeze(); return conv; }
            var crop = new CroppedBitmap(conv, new Int32Rect(cx, cy, side, side));
            var outPx = new byte[side * side * 4];
            crop.CopyPixels(outPx, side * 4, 0);
            var result = BitmapSource.Create(side, side, 96, 96, PixelFormats.Pbgra32, null, outPx, side * 4);
            result.Freeze();
            pixels = outPx;
            return result;
        }

        static BitmapSource Jumbo(string id)
        {
            IntPtr pidl; uint outAttr;
            if (Native.SHParseDisplayName("shell:AppsFolder\\" + id, IntPtr.Zero, out pidl, 0, out outAttr) != 0 || pidl == IntPtr.Zero) return null;
            try
            {
                var sfi = new Native.SHFILEINFO();
                if (Native.SHGetFileInfo(pidl, 0, ref sfi, (uint)Marshal.SizeOf(typeof(Native.SHFILEINFO)), 0x4000 /*SYSICONINDEX*/ | 0x8 /*PIDL*/) == IntPtr.Zero) return null;
                if (jumbo == null)
                {
                    Guid g = new Guid("46EB5926-582E-4017-9FDF-E8998DAA0950");
                    Native.SHGetImageList(4 /*SHIL_JUMBO*/, ref g, out jumbo);
                }
                if (jumbo == null) return null;
                IntPtr hicon;
                if (jumbo.GetIcon(sfi.iIcon, 1 /*ILD_TRANSPARENT*/, out hicon) != 0 || hicon == IntPtr.Zero) return null;
                try
                {
                    var bs = Imaging.CreateBitmapSourceFromHIcon(hicon, Int32Rect.Empty, BitmapSizeOptions.FromEmptyOptions());
                    bs.Freeze();
                    return bs;
                }
                finally { Native.DestroyIcon(hicon); }
            }
            finally { Marshal.FreeCoTaskMem(pidl); }
        }

        static string PackageRoot(string family)
        {
            if (packageRoots == null)
            {
                var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                var versions = new Dictionary<string, Version>(StringComparer.OrdinalIgnoreCase);
                using (var key = Registry.CurrentUser.OpenSubKey(@"Software\Classes\Local Settings\Software\Microsoft\Windows\CurrentVersion\AppModel\Repository\Packages"))
                {
                    if (key != null)
                        foreach (var full in key.GetSubKeyNames())
                        {
                            var parts = full.Split('_');
                            if (parts.Length != 5) continue;
                            if (parts[3].Length > 0 && parts[3] != "~") continue; // resource packs
                            string fam = parts[0] + "_" + parts[4];
                            Version v;
                            if (!Version.TryParse(parts[1], out v)) v = new Version(0, 0);
                            using (var sub = key.OpenSubKey(full))
                            {
                                var root = sub == null ? null : sub.GetValue("PackageRootFolder") as string;
                                if (root == null || !Directory.Exists(root)) continue;
                                Version old;
                                if (versions.TryGetValue(fam, out old) && old >= v) continue;
                                versions[fam] = v; map[fam] = root;
                            }
                        }
                }
                packageRoots = map;
            }
            string r;
            return packageRoots.TryGetValue(family, out r) ? r : null;
        }

        static BitmapSource UwpLogo(string aumid, out string bg)
        {
            bg = null;
            int bang = aumid.IndexOf('!');
            string root = PackageRoot(aumid.Substring(0, bang));
            string appId = aumid.Substring(bang + 1);
            if (root == null) return null;
            string manifest = Path.Combine(root, "AppxManifest.xml");
            if (!File.Exists(manifest)) return null;
            var doc = new XmlDocument();
            doc.Load(manifest);
            XmlElement app = null, ve = null;
            foreach (XmlNode n in doc.GetElementsByTagName("*"))
            {
                var e = n as XmlElement;
                if (e != null && e.LocalName == "Application" && e.GetAttribute("Id") == appId) { app = e; break; }
            }
            if (app == null) return null;
            foreach (XmlNode n in app.GetElementsByTagName("*"))
            {
                var e = n as XmlElement;
                if (e != null && e.LocalName == "VisualElements") { ve = e; break; }
            }
            if (ve == null) return null;
            bg = ve.GetAttribute("BackgroundColor");
            string best = null; double score = 0;
            Candidates(root, ve.GetAttribute("Square44x44Logo"), 44, 1.0, ref best, ref score);
            Candidates(root, ve.GetAttribute("Square150x150Logo"), 150, 0.5, ref best, ref score);
            return best == null ? null : LoadPng(best);
        }

        static void Candidates(string root, string rel, double basePx, double weight, ref string best, ref double score)
        {
            if (string.IsNullOrEmpty(rel)) return;
            string full = Path.Combine(root, rel);
            string dir = Path.GetDirectoryName(full);
            if (!Directory.Exists(dir)) return;
            string name = Path.GetFileNameWithoutExtension(full), ext = Path.GetExtension(full);
            foreach (var f in Directory.GetFiles(dir, name + "*" + ext))
            {
                string fn = Path.GetFileNameWithoutExtension(f).ToLowerInvariant();
                string q = fn.Substring(Math.Min(fn.Length, name.Length));
                if (q.Length > 0 && q[0] != '.') continue;
                if (q.Contains("contrast-") || q.Contains("lightunplated")) continue;
                double px = basePx;
                bool unplated = q.Contains("altform-unplated");
                var m = Regex.Match(q, @"targetsize-(\d+)");
                if (m.Success) px = int.Parse(m.Groups[1].Value);
                else
                {
                    var s = Regex.Match(q, @"scale-(\d+)");
                    if (s.Success) px = basePx * int.Parse(s.Groups[1].Value) / 100.0;
                }
                double sc = Math.Min(px, 256) * (unplated ? 3 : 1) * weight + px * 0.001;
                if (sc > score) { score = sc; best = f; }
            }
        }

        static BitmapSource LoadPng(string path)
        {
            BitmapImage bi = null;
            for (int pass = 0; pass < 2; pass++)
            {
                using (var fs = File.OpenRead(path))
                {
                    bi = new BitmapImage();
                    bi.BeginInit();
                    bi.CacheOption = BitmapCacheOption.OnLoad;
                    bi.StreamSource = fs;
                    if (pass == 1) bi.DecodePixelWidth = 256;
                    bi.EndInit();
                    bi.Freeze();
                }
                if (bi.PixelWidth <= 320) break;
            }
            return bi;
        }
    }

    static class Colorx
    {
        public static void ToHsv(double r, double g, double b, out double h, out double s, out double v)
        {
            r /= 255; g /= 255; b /= 255;
            double mx = Math.Max(r, Math.Max(g, b)), mn = Math.Min(r, Math.Min(g, b)), d = mx - mn;
            v = mx; s = mx == 0 ? 0 : d / mx;
            if (d == 0) h = 0;
            else if (mx == r) h = 60 * (((g - b) / d) % 6);
            else if (mx == g) h = 60 * ((b - r) / d + 2);
            else h = 60 * ((r - g) / d + 4);
            if (h < 0) h += 360;
        }

        public static Color FromHsv(double h, double s, double v)
        {
            h = ((h % 360) + 360) % 360;
            double c = v * s, x = c * (1 - Math.Abs((h / 60) % 2 - 1)), m = v - c, r, g, b;
            if (h < 60) { r = c; g = x; b = 0; }
            else if (h < 120) { r = x; g = c; b = 0; }
            else if (h < 180) { r = 0; g = c; b = x; }
            else if (h < 240) { r = 0; g = x; b = c; }
            else if (h < 300) { r = x; g = 0; b = c; }
            else { r = c; g = 0; b = x; }
            return Color.FromRgb((byte)((r + m) * 255), (byte)((g + m) * 255), (byte)((b + m) * 255));
        }

        public static Color Scale(Color c, double f)
        {
            return Color.FromRgb((byte)Math.Min(255, c.R * f), (byte)Math.Min(255, c.G * f), (byte)Math.Min(255, c.B * f));
        }

        public static Color Mix(Color a, Color b, double t)
        {
            return Color.FromRgb((byte)(a.R + (b.R - a.R) * t), (byte)(a.G + (b.G - a.G) * t), (byte)(a.B + (b.B - a.B) * t));
        }

        public static Color WithAlpha(Color c, double a) { return Color.FromArgb((byte)Math.Max(0, Math.Min(255, a * 255)), c.R, c.G, c.B); }

        public static SolidColorBrush Brush(Color c) { var b = new SolidColorBrush(c); b.Freeze(); return b; }
        public static SolidColorBrush Brush(byte a, byte r, byte g, byte b) { return Brush(Color.FromArgb(a, r, g, b)); }

        public static bool TryParse(string hex, out Color c)
        {
            c = Colors.Black;
            if (string.IsNullOrEmpty(hex)) return false;
            hex = hex.TrimStart('#');
            if (hex.Length != 6) return false;
            try { c = Color.FromRgb(Convert.ToByte(hex.Substring(0, 2), 16), Convert.ToByte(hex.Substring(2, 2), 16), Convert.ToByte(hex.Substring(4, 2), 16)); return true; }
            catch { return false; }
        }

        public static string Hex(Color c) { return c.R.ToString("X2") + c.G.ToString("X2") + c.B.ToString("X2"); }

        public static int Distance(Color a, Color b) { return Math.Abs(a.R - b.R) + Math.Abs(a.G - b.G) + Math.Abs(a.B - b.B); }

