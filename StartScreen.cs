    // 8.1-style colour picker: a strip of hues, and a grid of shades for the chosen hue.
    // Hue is continuous (0-360); the far-left of the strip is the greys (hue = -1).
    static class Palette
    {
        const double GreyZone = 0.07;
        static readonly double[] Sats = { 1.0, 0.85, 0.70, 0.55, 0.40, 0.25 };

        public static double HueAt(double x) { return x < GreyZone ? -1 : Math.Min(359.9, (x - GreyZone) / (1 - GreyZone) * 360); }
        public static double XOf(double hue) { return hue < 0 ? GreyZone / 2 : GreyZone + hue / 360 * (1 - GreyZone); }

        static Brush strip;
        public static Brush StripBrush()
        {
            if (strip != null) return strip;
            var g = new LinearGradientBrush { StartPoint = new Point(0, 0.5), EndPoint = new Point(1, 0.5) };
            var grey = Color.FromRgb(0x80, 0x80, 0x80);
            g.GradientStops.Add(new GradientStop(grey, 0));
            g.GradientStops.Add(new GradientStop(grey, GreyZone - 0.002));
            for (int h = 0; h <= 360; h += 15) g.GradientStops.Add(new GradientStop(Colorx.FromHsv(h % 360, 0.9, 0.85), XOf(h)));
            g.Freeze();
            strip = g;
            return g;
        }

        public static Color Background(double hue, int shade)
        {
            int row = shade / 6, col = shade % 6;
            if (hue < 0) return Colorx.FromHsv(0, 0, 0.34 - shade * 0.018);
            double[] vs = { 0.44, 0.31, 0.20 };
            return Colorx.FromHsv(hue, Sats[col], vs[row]);
        }

        public static Color Accent(double hue, int shade)
        {
            int row = shade / 6, col = shade % 6;
            if (hue < 0) return Colorx.FromHsv(0, 0, 1.0 - shade * 0.065);
            double[] vs = { 0.96, 0.74 };
            return Colorx.FromHsv(hue, Sats[col], vs[row]);
        }

        public static void Nearest(Color c, bool accent, out double hue, out int shade)
        {
            double h, s, v;
            Colorx.ToHsv(c.R, c.G, c.B, out h, out s, out v);
            hue = s < 0.12 ? -1 : h;
            shade = 0; int best = int.MaxValue;
            for (int k = 0; k < (accent ? 12 : 18); k++)
            {
                int d = Colorx.Distance(c, accent ? Accent(hue, k) : Background(hue, k));
                if (d < best) { best = d; shade = k; }
            }
        }
    }

